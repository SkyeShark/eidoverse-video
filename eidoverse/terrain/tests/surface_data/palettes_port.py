"""Write build/palettes.js's data block from the Blender edition's build/palettes.py (PORT_PLAN.md 3.5: the palettes
are data, ported as Blender's surfacing round leaves them; the port does not tune looks).

    <Blender's python> -I eidoverse/terrain/tests/surface_data/palettes_port.py [--commit <name>] [--check]

The Blender edition is found as tests/parity/_blender.py finds it ($EIDO_BLENDER_EDITION, or blender/ in this
checkout) and is only read. palettes.py is imported (numpy only) and every module-level value that is data (dicts,
lists, tuples, strings, numbers, booleans, None: its tables and the template strings its looks are built from) is
written, in palettes.py's order, as `export const NAME = <JSON>;` between build/palettes.js's markers, tuples as
arrays. Its functions are build/palettes.js's own code, ported by hand. --commit names the Blender commit in the
block's first line (default: the edition's HEAD when it is a git checkout, else $EIDO_SURFACE_COMMIT). --check writes
nothing and exits 1 when the block differs from what palettes.py gives (what changed since the port).
"""
from __future__ import annotations

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'parity'))
import _blender as B  # noqa: E402

TARGET = os.path.normpath(os.path.join(HERE, '..', '..', 'build', 'palettes.js'))
START = '// <palettes data: generated by tests/surface_data/palettes_port.py; do not edit by hand>'
END = '// palettes data>'
SKIP = {'_OPS', '_HEX', '_SURFACE_NAMES', '__all__'}


def data_names(P):
    import types
    out = []
    for name, v in vars(P).items():
        if name.startswith('__') or name in SKIP:
            continue
        if isinstance(v, (types.ModuleType, types.FunctionType, type)) or callable(v):
            continue
        if isinstance(v, (dict, list, tuple, str, int, float, bool)) or v is None:
            out.append(name)
    return out


def fmt(v, depth=0, width=116):
    """JSON with a list of numbers and a short object on one line, and one entry a line otherwise."""
    flat = json.dumps(v, ensure_ascii=False, separators=(', ', ': '))
    if not isinstance(v, (dict, list)) or len(flat) + 4 * depth <= width:
        return flat
    pad, inner = '    ' * depth, '    ' * (depth + 1)
    if isinstance(v, list):
        return '[\n' + ',\n'.join(inner + fmt(x, depth + 1, width) for x in v) + '\n' + pad + ']'
    return '{\n' + ',\n'.join(inner + json.dumps(k) + ': ' + fmt(x, depth + 1, width) for k, x in v.items()) + '\n' + pad + '}'


def block(P, commit):
    lines = [START, f'// from blender/eidoblend/terrain/build/palettes.py at {commit}: its module-level data, in its order']
    for name in data_names(P):
        js = fmt(B.jsonable(getattr(P, name)))
        lines.append(f'export const {name} = {js};')
    lines.append(END)
    return '\n'.join(lines)


def main():
    a = B.script_args()
    edition = B.bare_terrain_package()
    from eidoblend.terrain.build import palettes as P
    commit = a[a.index('--commit') + 1] if '--commit' in a else (
        B.git(edition, 'rev-parse', '--short', 'HEAD') or os.environ.get('EIDO_SURFACE_COMMIT') or 'unknown')
    with open(TARGET, encoding='utf-8') as f:
        text = f.read()
    i, j = text.index(START), text.index(END) + len(END)
    new = text[:i] + block(P, commit) + text[j:]
    if '--check' in a:
        same = new == text
        print(f'[palettes_port] build/palettes.js data {"equals" if same else "differs from"} palettes.py at {commit}')
        return 0 if same else 1
    with open(TARGET + '.tmp', 'w', encoding='utf-8', newline='\n') as f:
        f.write(new)
    os.replace(TARGET + '.tmp', TARGET)
    print(f'[palettes_port] wrote {len(data_names(P))} tables of palettes.py at {commit} into build/palettes.js')
    return 0


if __name__ == '__main__':
    sys.exit(main())
