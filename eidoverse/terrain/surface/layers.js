// Port of blender/eidoblend/terrain/surface/atlas.py at d67f19e, with the atlas half of surface/__init__.py
// (SurfaceData.tile, _gutter, _array, _channel_array, _encode, atlas(), images()).
//
// The surface data's textures (SURFACING_DESIGN.md 2.2, 2.6, 2.7; PORT_PLAN.md 3.5): per family one
// THREE.DataArrayTexture, one layer per level, each level a square tile of its maps with a gutter of real terrain data
// around it, so linear filtering and the mips at a tile's edge read the ground there.
//
//     import { makeTextures, layerArrays, lutTexture } from './surface/layers.js';
//     const tex = await makeTextures(sd);      // { D, E, M0.., F, C, P: THREE.DataArrayTexture } (SurfaceData.textures)
//     const L = await layerArrays(sd, 'E');    // { data, size, layers, format, colorspace }: the texture's bytes
//     lutTexture(palette)                      // the palette's ramps (palettes.rampRows), 256 x rows RGBA8 sRGB
//
// Tiles (atlas.py). A level of n texels a side (texel = side / n) gets a tile of n + 2 g texels, g = 32 up to 1024
// texels and 64 above (index.js gutterFor). The data sits in the middle; the gutter holds the coarser levels' maps at
// the gutter texels' own world positions (the outermost level edge-extended), so a read at the window's edge, or a mip
// that averages across it, sees real terrain data. Each tile sits in its layer's corner; a layer is as large as the
// family's largest tile (index.js layoutOf).
//
// UV. Rows run south to north as the arrays' rows (row 0 at v = 0: the texture is not flipped), so level i's texel
// (a, b) is layer i's pixel (g + a, g + b), and world (x, y) inside the window reads
//     u = u0 + du (x - x0) / side,   v = v0 + dv (y - y0) / side,   layer = i,
//     u0 = (x + g) / S, v0 = (y + g) / S, du = dv = n / S   (S the layer's size; SurfaceData.readerConstants);
// a texel centre lands on a pixel centre exactly.
//
// Formats (maps.FAMILIES): D and F RGBA16F (HalfFloatType: the 16F families are half on the GPU, as their encodings
// assume), E and M RGBA8, C and P RGBA8 with the colour channels sRGB-encoded (SRGBColorSpace: the GPU decodes them;
// their fourth channel, roughness or share, linear). Four independent data channels in every family. Linear filtering
// with mips (generated by three.js from the layer data), clamped at the edges.
//
// Where this differs from atlas.py and __init__.py, and why:
//   - Layers of a 2D-array texture, not shelves of one tall image (PORT_PLAN.md 3.5: a film D atlas is taller than a
//     default device's 8,192 texels). No image files: the textures are made from the bake on the GPU in one pass a
//     family (the edition's rule: per-texel work is GPU compute), read back once and handed to three.js, which uploads
//     them; Blender writes EXR and PNG files beside the bake and loads them.
//   - Each tile is built on the GPU (kernels/atlas/tile.wgsl, tile_encode.wgsl, resample.wgsl): the data region
//     resampled (atlas.resample: equal, x2 bilinear, 2 x 2 box), the gutter bilinear on the coarser levels
//     (atlas.sample_lattice's arithmetic, its affine texel coordinates folded in doubles: exact for nested levels),
//     the family's encoding and the bytes. _gutter stops searching coarser levels once every gutter texel has found
//     one; here the search stops at the first level whose window holds the whole tile (the same levels whenever one
//     window holds the tile, which nesting gives; a tile only a union of windows covers would search further).
//   - The LUT (lutTexture) is the plan's "plain 256 x rows RGBA8 texture" of palettes.rampRows (Blender's material
//     makes its image in build/surfacing.py, _lut_image): a small table, converted to bytes on the GPU too.

import * as MP from './maps.js';
import * as B from './bake.js';
import { NEUTRAL } from './index.js';
import { ValueError } from '../core/levels.js';

const f32 = Math.fround;
const KIND = { float: 0, unit: 1, signed: 2, bend: 3, thick: 4, z: 5, srgb: 6, zero: 7 };

/** { family: THREE.DataArrayTexture } of a SurfaceData (module doc). opts: THREE (the three module the renderer
 * uses; default import('three/webgpu')), R (the GPU runner; default core/gpu.js init()). */
export async function makeTextures(sd, opts = {}) {
    const THREE = opts.THREE ?? await import('three/webgpu');
    const R = opts.R ?? await (await import('../core/gpu.js')).init();
    const out = {};
    const t0 = performance.now();
    for (const fam of sd.families()) {
        const L = await layerArrays(sd, fam, { R });
        const tex = new THREE.DataArrayTexture(L.data, L.size, L.size, L.layers);
        tex.format = THREE.RGBAFormat;
        tex.type = L.format === 'RGBA16F' ? THREE.HalfFloatType : THREE.UnsignedByteType;
        tex.colorSpace = L.colorspace === 'sRGB' ? THREE.SRGBColorSpace : THREE.NoColorSpace;
        tex.magFilter = THREE.LinearFilter;
        tex.minFilter = THREE.LinearMipmapLinearFilter;
        tex.generateMipmaps = true;
        tex.wrapS = tex.wrapT = THREE.ClampToEdgeWrapping;
        tex.flipY = false;
        tex.unpackAlignment = 4;
        tex.name = `eido_surf_${String(sd.key).slice(0, 8)}_${fam}`;
        tex.userData = { eido_family: fam, eido_maps: sd.familyMaps(fam), layout: sd.layouts[fam].toDict() };
        tex.needsUpdate = true;
        out[fam] = tex;
    }
    sd.info.texture_seconds = +((performance.now() - t0) / 1000).toFixed(3);
    return out;
}

/** The family's texture data: { data (Uint8Array RGBA8, or Uint16Array of halves RGBA16F: layers x size x size x 4),
 * size, layers, format, colorspace, seconds }, every level's tile in its layer's corner. */
export async function layerArrays(sd, fam, { R }) {
    const t0 = performance.now();
    const lay = sd.layouts[fam];
    const base = fam.startsWith('M') ? 'M' : fam;
    const spec = MP.FAMILIES[base];
    const half = spec.format === 'RGBA16F';
    const S = lay.size;
    const words = [];
    for (const t of lay.tiles) words.push(await tileWords(sd, fam, t, S, half, R));
    const got = await R.readAll(words);
    for (const w of words) w.destroy();
    const per = S * S * 4;                                   // channels per layer
    const data = half ? new Uint16Array(per * lay.tiles.length) : new Uint8Array(per * lay.tiles.length);
    got.forEach((g, k) => {
        const view = half ? new Uint16Array(g.buffer, g.byteOffset, per) : new Uint8Array(g.buffer, g.byteOffset, per);
        data.set(view, k * per);
    });
    return { data, size: S, layers: lay.tiles.length, format: spec.format, colorspace: spec.colorspace,
        seconds: +((performance.now() - t0) / 1000).toFixed(3) };
}

// the four channels of a family's tile: [source map, channel of a colour or null] (SurfaceData.tile)
function channelsOf(sd, fam) {
    if (fam === 'C' || fam === 'P') {
        const key = fam === 'C' ? 'far_colour' : 'down_colour', alpha = fam === 'C' ? 'far_roughness' : 'down_share';
        return [[key, 0], [key, 1], [key, 2], [alpha, null]];
    }
    return sd.familyMaps(fam).map((nm) => [nm === null ? null : (fam === 'F' && nm === 'src_strata') ? 'src_dz'
        : (fam === 'F' && nm === 'strata') ? 'strata_dz' : nm, null]);
}

/** Level t.level's tile of a family as its layer's words (an r32ui field: S x S, or S x 2 S for halves). */
async function tileWords(sd, fam, t, S, half, R) {
    const i = t.level;
    const names = (fam === 'C' || fam === 'P') ? [null, null, null, null] : sd.familyMaps(fam);
    const chans = channelsOf(sd, fam);
    const fields = [], kinds = [], scales = [];
    for (let c = 0; c < 4; c++) {
        const [src, ch] = chans[c];
        if (src === null) {
            fields.push(null);
            kinds.push(KIND.zero);
            scales.push(0);
            continue;
        }
        const full = R.field(t.size, t.size, 1);
        const own = await arrayField(sd, R, i, src, ch);
        if (own === null) {
            run(R, 'atlas/tile', {}, full, { uMode: 3, uG: t.gutter, uN: t.n, uWin: [NEUTRAL[src] ?? 0.0, 0, 0, 0] });
        } else {
            const res = resampled(R, own, t.n);
            run(R, 'atlas/tile', { src: res }, full, { uMode: 0, uG: t.gutter, uN: t.n });
            res.destroy();
            own.destroy();
        }
        await gutter(sd, R, i, src, ch, full, t);
        fields.push(full);
        if (fam === 'C' || fam === 'P') {
            kinds.push(c < 3 ? KIND.srgb : KIND.float);
            scales.push(0);
        } else if (fam === 'F') {
            kinds.push(KIND.z);
            scales.push(f32((sd.refs[names[c]] ?? [])[i] ?? 0.0));
        } else {
            const s = MP.spec(names[c]);
            kinds.push(KIND[s.encoding] ?? KIND.float);
            scales.push(s.encoding === 'bend' ? f32(MP.bendScale(s, Number(sd.levels[i].cell)))
                : s.encoding === 'thick' ? f32(1.0 / s.t_max) : 0);
        }
    }
    const words = R.field(S, half ? 2 * S : S, 1, null, 'u32');
    const stand = R.field(1, 1, 1);
    const samp = {};
    fields.forEach((f, c) => { samp[`c${c}`] = f ?? stand; });
    R.run(B.kernel(R, 'atlas/tile_encode'), samp, { outW: words }, { uKinds: kinds, uScales: scales.map(f32), uFormat: half ? 1 : 0,
        uSize: t.size });
    stand.destroy();
    for (const f of fields) if (f) f.destroy();
    return words;
}

function run(R, name, samplers, out, uniforms) {
    const k = B.kernel(R, name);
    const D = R.field(1, 1, 1);
    const s = {};
    for (const nm of k.spec.samplers) s[nm] = samplers[nm] ?? D;
    const u = { uMode: 0, uG: 0, uN: 0, uMap: [0, 0, 0, 0], uWin: [0, 0, 0, 0], ...uniforms };
    R.run(k, s, { outT: out }, u);
    D.destroy();
}

/** A map of level i as physical values on its own grid (an r32f GPU field), or null when the level lacks it
 * (SurfaceData._array: the F family's metres above the ground for strata_dz; a colour's channel ch). */
async function arrayField(sd, R, i, name, ch) {
    const m = await sd.maps(i);
    let a = m[name];
    if (name === 'strata_dz' && (a === undefined || a === null) && m.strata) {
        // _dz: (strata - h), in doubles then float32: the GPU's float32 difference of two float32 values is the same
        const h = sd.terrain.fields(i).h;
        const n = sd.levels[i].n;
        const fs = R.field(n, n, 1, m.strata), fh = R.field(n, n, 1, h instanceof Float32Array ? h : new Float32Array(h));
        const out = (await import('../core/grid.js')).arith(R, 'sub', fs, fh);
        fs.destroy();
        fh.destroy();
        return out;
    }
    if (a === undefined || a === null) return null;
    if (ch !== null && ch !== undefined) {
        const [h, w3] = [a.shape3[0], a.shape3[1] * a.shape3[2]];
        const flat = R.field(h, w3, 1, a);
        const rgba = R.field(h, a.shape3[1], 4);
        R.run(B.kernel(R, 'atlas/deinterleave'), { src: flat }, { outR: rgba }, {});
        flat.destroy();
        const one = R.field(h, a.shape3[1], 1);
        R.run(B.kernel(R, 'pick'), { a: rgba }, { outF: one }, { uCh: ch, uOffset: [0, 0] });
        rgba.destroy();
        return one;
    }
    const n = Math.round(Math.sqrt(a.length));
    return R.field(n, n, 1, a);
}

/** atlas.resample: a map (m texels) on n texels over the same window: itself, x2 bilinear, or a 2 x 2 box average. */
function resampled(R, f, n) {
    const m = f.h;
    if (m === n) {
        const c = R.field(n, n, 1);
        R.run(B.kernel(R, 'pick'), { a: f }, { outF: c }, { uCh: 0, uOffset: [0, 0] });
        return c;
    }
    if (n !== 2 * m && m !== 2 * n) throw new ValueError(`a map of ${m} texels cannot be put on a grid of ${n} (only x2, /2 or equal)`);
    const r = R.field(n, n, 4);
    R.run(B.kernel(R, 'atlas/resample'), { src: f }, { outR: r }, { uMode: n === 2 * m ? 1 : 0 });
    const one = R.field(n, n, 1);
    R.run(B.kernel(R, 'pick'), { a: r }, { outF: one }, { uCh: 0, uOffset: [0, 0] });
    r.destroy();
    return one;
}

/** The tile's gutter from the coarser levels (SurfaceData._gutter): each gutter texel the finest level (by index)
 * below this one whose window holds its centre, bilinear there, clamped to its outermost centres; level 0 reads
 * itself (edge extension). A level the search reaches that lacks the map gives the whole gutter NEUTRAL. */
async function gutter(sd, R, i, name, ch, full, t) {
    const g = t.gutter, s = t.size, tex = t.texel;
    const lo = [t.x0 + (0.5 - g) * tex, t.y0 + (0.5 - g) * tex];
    const hi = [t.x0 + (s - 1 - g + 0.5) * tex, t.y0 + (s - 1 - g + 0.5) * tex];
    const src = i === 0 ? [0] : Array.from({ length: i }, (_x, k) => i - 1 - k);
    const use = [];
    for (const k of src) {
        const f = await arrayField(sd, R, k, name, ch);
        if (f === null) {
            for (const [, x] of use) x.destroy();
            run(R, 'atlas/tile', {}, full, { uMode: 3, uG: g, uN: t.n, uWin: [NEUTRAL[name] ?? 0.0, 1, 0, 0] });
            return;
        }
        use.push([k, f]);
        const lv = sd.levels[k];
        if (k === 0) break;
        const x1 = Number(lv.x0) + Number(lv.side), y1 = Number(lv.y0) + Number(lv.side);
        if (Number(lv.x0) <= lo[0] && hi[0] <= x1 && Number(lv.y0) <= lo[1] && hi[1] <= y1) break;
    }
    // coarsest first: it fills every gutter texel, then each finer level the texels its window holds
    for (let q = use.length - 1; q >= 0; q--) {
        const [k, f] = use[q];
        const lv = sd.levels[k];
        const tk = Number(lv.side) / f.h;
        const ax = (t.x0 + (0.5 - g) * tex - Number(lv.x0)) / tk - 0.5, ay = (t.y0 + (0.5 - g) * tex - Number(lv.y0)) / tk - 0.5;
        const win = [(Number(lv.x0) - t.x0) / tex + g - 0.5, (Number(lv.y0) - t.y0) / tex + g - 0.5,
            (Number(lv.x0) + Number(lv.side) - t.x0) / tex + g - 0.5, (Number(lv.y0) + Number(lv.side) - t.y0) / tex + g - 0.5];
        run(R, 'atlas/tile', { src: f }, full, { uMode: q === use.length - 1 ? 1 : 2, uG: g, uN: t.n,
            uMap: [f32(ax), f32(tex / tk), f32(ay), f32(tex / tk)], uWin: win.map(f32) });
        f.destroy();
    }
}

/** The palette's ramps (palettes.rampRows: sRGB-encoded rows) as a 256 x rows RGBA8 texture (SRGBColorSpace,
 * nearest along the rows, linear along t, clamped), with its index in userData. opts: THREE, R. */
export async function lutTexture(pal, opts = {}) {
    const THREE = opts.THREE ?? await import('three/webgpu');
    const R = opts.R ?? await (await import('../core/gpu.js')).init();
    const P = await B.palettesModule();
    const [rows, index] = P.rampRows(pal);
    const width = 256, nr = Math.max(1, rows.length / (width * 4));
    const src = R.field(nr, width, 4, rows.length ? rows : new Float32Array(width * 4));
    const chans = R.unpack(src, ['r', 'g', 'b', 'a']);
    src.destroy();
    const words = R.field(nr, width, 1, null, 'u32');
    R.run(B.kernel(R, 'atlas/tile_encode'), { c0: chans.r, c1: chans.g, c2: chans.b, c3: chans.a }, { outW: words },
        { uKinds: [0, 0, 0, 0], uScales: [0, 0, 0, 0], uFormat: 0, uSize: Math.max(width, nr) });
    for (const f of Object.values(chans)) f.destroy();
    const [w] = await R.readAll([words]);
    words.destroy();
    const tex = new THREE.DataTexture(new Uint8Array(w.buffer, w.byteOffset, nr * width * 4), width, nr, THREE.RGBAFormat, THREE.UnsignedByteType);
    tex.colorSpace = THREE.SRGBColorSpace;
    tex.magFilter = THREE.NearestFilter;
    tex.minFilter = THREE.NearestFilter;
    tex.wrapS = tex.wrapT = THREE.ClampToEdgeWrapping;
    tex.flipY = false;
    tex.userData = { index };
    tex.needsUpdate = true;
    return tex;
}
