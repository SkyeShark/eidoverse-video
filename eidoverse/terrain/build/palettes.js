// Python's str() of a template argument: an integer without '.0' (JavaScript cannot tell 40.0 from 40)
const fmt = (template, values) => template.replace(/\{(\w+)\}/g, (m, k) => (k in values ? String(values[k]) : m));

/** A cliff weight bared from `lo` to `hi` degrees; ribs: a factor on the convex-rib term (palettes.py _cliff). */
