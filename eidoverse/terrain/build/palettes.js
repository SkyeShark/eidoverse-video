function nearest(name, options, k = 3) {
    const dist = (a, b) => {
        let prev = Array.from({ length: b.length + 1 }, (_, i) => i);
        for (let i = 1; i <= a.length; i++) {
            const cur = [i];
            for (let j = 1; j <= b.length; j++) cur.push(Math.min(prev[j] + 1, cur[j - 1] + 1, prev[j - 1] + (a[i - 1] !== b[j - 1] ? 1 : 0)));
            prev = cur;
        }
        return prev[prev.length - 1];
    };
    return [...options].map((o, i) => [dist(String(name), o), i, o]).sort((p, q) => p[0] - q[0] || p[1] - q[1]).slice(0, k).map((t) => t[2]);
}

