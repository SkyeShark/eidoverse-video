function smooth1(e0, e1, x) {
    if (e1 === e0) return x >= e0 ? 1.0 : 0.0;
    const t = Math.min(Math.max((x - e0) / (e1 - e0), 0.0), 1.0);
    return t * t * (3.0 - 2.0 * t);
}

// a 32-bit integer hash of a lattice point -> 0..1 (palettes.py _hash2, numpy int64 arithmetic: the products stay
// under 2^53, the second product's low 32 bits are Math.imul's)
function hash2(ix, iy, seed) {
    let h = (ix * 374761393 + iy * 668265263 + Math.trunc(seed) * 2147483647);
    h = Number(BigInt.asUintN(32, BigInt(h)));
    h = Math.imul((h ^ (h >>> 13)) >>> 0, 1274126177) >>> 0;
    h = (h ^ (h >>> 16)) >>> 0;
    return (h & 0xffffff) / 0xffffff;
}

/** palettes.py value_noise at one point: a world-space value noise of about 0..1 (mean 0.5), features scale_m
 * metres across (the scatter's noise() and fbm()). */
export function valueNoise(x, y, scaleM, seed = 0, octaves = 2, gain = 0.5, stretch = 1.6) {
    x = Number(x) / Math.max(scaleM, 1e-9);
    y = Number(y) / Math.max(scaleM, 1e-9);
    let tot = 0.0, amp = 1.0, norm = 0.0;
    for (let o = 0; o < octaves; o++) {
        const ix = Math.floor(x), iy = Math.floor(y);
        const fx = x - ix, fy = y - iy;
        const ux = fx * fx * fx * (fx * (fx * 6 - 15) + 10), uy = fy * fy * fy * (fy * (fy * 6 - 15) + 10);
        const s = seed * 31 + o * 17;
        const v00 = hash2(ix, iy, s), v10 = hash2(ix + 1, iy, s);
        const v01 = hash2(ix, iy + 1, s), v11 = hash2(ix + 1, iy + 1, s);
        const v = (v00 * (1 - ux) + v10 * ux) * (1 - uy) + (v01 * (1 - ux) + v11 * ux) * uy;
        tot = tot + amp * v;
        norm += amp;
        amp *= gain;
        x = x * 2.0 + 17.3;
        y = y * 2.0 - 9.1;
    }
    const v = tot / norm;
    return Math.min(Math.max(0.5 + (v - 0.5) * stretch, 0.0), 1.0);
}

/** palettes.py voronoi_cells at one point: a random value 0..1 per cell of a world-space Voronoi partition, cells
 * about scale_m across; with z (metres) and zStretch k > 0 a partition of (x, y, k z). */
export function voronoiCells(x, y, scaleM, seed = 0, z = null, zStretch = 0.0) {
    const gx = Number(x) / Math.max(scaleM, 1e-9), gy = Number(y) / Math.max(scaleM, 1e-9);
    const three = z !== null && z !== undefined && zStretch > 0.0;
    const gz = three ? Number(z) * Number(zStretch) / Math.max(scaleM, 1e-9) : 0;
    const ix = Math.floor(gx), iy = Math.floor(gy), iz = three ? Math.floor(gz) : 0;
    let best = Infinity, val = 0.0;
    for (const dk of (three ? [-1, 0, 1] : [0])) {
        for (const dj of [-1, 0, 1]) {
            for (const di of [-1, 0, 1]) {
                const cx = ix + di, cy = iy + dj;
                let d, v;
                if (three) {
                    const cz = iz + dk;
                    const salt = ((cz * 7919) % 104729 + 104729) % 104729;
                    const px = cx + hash2(cx, cy + salt, seed * 13 + 1);
                    const py = cy + hash2(cx, cy + salt, seed * 13 + 2);
                    const pz = cz + hash2(cx, cy + salt, seed * 13 + 4);
                    d = (gx - px) ** 2 + (gy - py) ** 2 + (gz - pz) ** 2;
                    v = hash2(cx, cy + salt, seed * 13 + 3);
                } else {
                    const px = cx + hash2(cx, cy, seed * 13 + 1);
                    const py = cy + hash2(cx, cy, seed * 13 + 2);
                    d = (gx - px) ** 2 + (gy - py) ** 2;
                    v = hash2(cx, cy, seed * 13 + 3);
                }
                if (d < best) {
                    best = d;
                    val = v;
                }
            }
        }
    }
    return val;
}

/** An expression at one point (palettes.py evaluate, per point: module doc). masks: { name: number } or a function
 * name -> number; opts: x, y (world metres, for noise(), fbm() and cells()), constants, flat (noise at its mean
 * 0.5). A mask the object lacks reads 0. */
export function evaluate(expr, masks, opts = {}) {
    const t = Array.isArray(expr) ? expr : parse(expr);
    const get = typeof masks === 'function' ? masks : (n) => masks[n];
    const consts = { ...CONSTANTS, ...(opts.constants ?? {}) };
    const { x = null, y = null, flat = false } = opts;
    const ev = (n) => {
        const k = n[0];
        if (k === 'num') return n[1];
        if (k === 'const') return Number(consts[n[1]]);
        if (k === 'mask') {
            const v = get(n[1]);
            return v === undefined || v === null ? 0.0 : Number(v);
        }
        if (k === 'neg') return -ev(n[1]);
        if (k === 'op') {
            const a = ev(n[2]), b = ev(n[3]);
            if (n[1] === '+') return a + b;
            if (n[1] === '-') return a - b;
            if (n[1] === '*') return a * b;
            return a / (Math.abs(b) > 1e-12 ? b : 1e-12);
        }
        const [, f, args] = n;
        if (['noise', 'fbm', 'cells'].includes(f)) {
            if (flat) return 0.5;
            if (x === null) throw new ExprError(`${f}() needs the point (x, y) to evaluate`);
            const seed = args.length > 1 ? Math.trunc(args[1][1]) : 0;
            if (f === 'cells') {
                const kz = args.length > 2 ? Number(args[2][1]) : 0.0;
                const zh = kz > 0.0 ? get('height') : null;
                if (kz > 0.0 && (zh === undefined || zh === null)) throw new ExprError('cells(scale_m, seed, z_stretch) needs the height');
                return voronoiCells(x, y, args[0][1], seed, zh, kz);
            }
            if (f === 'fbm') return valueNoise(x, y, args[0][1], seed + 101, 5, 0.6, 2.2);
            return valueNoise(x, y, args[0][1], seed);
        }
        const v = args.map(ev);
        if (f === 'smoothstep') return smooth1(v[0], v[1], v[2]);
        if (f === 'min') return Math.min(...v);
        if (f === 'max') return Math.max(...v);
        if (f === 'clamp') return Math.min(Math.max(v[0], v[1]), v[2]);
        if (f === 'abs') return Math.abs(v[0]);
        if (f === 'pow') return Math.max(v[0], 0.0) ** v[1];
        if (f === 'mix') return v[0] + (v[1] - v[0]) * v[2];
        throw new ExprError(f);
    };
    return ev(t);
}


