/** A ramp's stops as [t (numbers), linear rgb ([r, g, b] per stop), kind ('colour' | 'tint')]. */
export function rampStops(ramp) {
    const stops = [...((ramp ?? {}).stops ?? [])];
    if (stops.length < 2) throw new ValueError('a ramp needs at least two stops [(t, colour), ...]');
    const ts = [], cs = [], kinds = new Set();
    for (const s of stops) {
        if (!(Array.isArray(s) && s.length === 2)) throw new ValueError(`ramp stop ${pyReprValue(s)}: write it as (t, colour)`);
        const [t, c] = s;
        ts.push(Number(t));
        if (typeof c === 'string') {
            cs.push(hexLinear(c));
            kinds.add('colour');
        } else {
            const cc = [...c].map(Number);
            if (cc.length !== 3) throw new ValueError(`ramp stop colour ${pyReprValue(c)}: sRGB "#rrggbb" or an (r, g, b) multiplier`);
            cs.push(cc);
            kinds.add('tint');
        }
    }
    if (kinds.size !== 1) throw new ValueError('a ramp mixes sRGB colours and (r, g, b) multipliers: use one kind');
    if (ts[0] < 0.0 || ts[ts.length - 1] > 1.0 || ts.some((v, k) => k > 0 && v - ts[k - 1] <= 0.0)) {
        throw new ValueError(`ramp stops at t = ${JSON.stringify(ts)}: t must rise within 0..1`);
    }
    return [ts, cs, [...kinds][0]];
}

/** The ramp's linear [r, g, b] at t (clamped to 0..1): straight between the stops, or eased when the ramp says
 * smooth. */
export function rampValue(ramp, t) {
    const [ts, cs] = rampStops(ramp);
    t = Math.min(Math.max(Number(t), 0.0), 1.0);
    const out = [...cs[0]];
    for (let k = 1; k < ts.length; k++) {
        let s = Math.min(Math.max((t - ts[k - 1]) / (ts[k] - ts[k - 1]), 0.0), 1.0);
        if (ramp.smooth) s = s * s * (3.0 - 2.0 * s);
        for (let c = 0; c < 3; c++) out[c] += s * (cs[k][c] - cs[k - 1][c]);
    }
    return out;
}

// Python's repr of a float, as palettes.py writes a stop into an expression (f'{a!r}')
function pyFloatRepr(v) {
    v = Number(v);
    if (Number.isInteger(v)) return v.toFixed(1);
    const s = String(v);
    if (/e/.test(s)) {
        const [m, e] = s.split('e');
        const ex = Number(e);
        return `${m}e${ex < 0 ? '-' : '+'}${String(Math.abs(ex)).padStart(2, '0')}`;
    }
    return s;
}

function rampSegments(ramp, centre, tag) {
    const [ts, cs] = rampStops(ramp);
    const t = String(ramp.t);
    const out = [];
    const first = cs[0].map((v, c) => v / Math.max(Number(centre[c]), 1e-4));
    if (Math.max(...first.map((v) => Math.abs(v - 1.0))) > 1e-6) out.push({ scale_m: null, tint: first, amount: 1.0, from_ramp: tag });
    for (let k = 1; k < ts.length; k++) {
        const ratio = cs[k].map((v, c) => v / Math.max(cs[k - 1][c], 1e-4));
        if (Math.max(...ratio.map((v) => Math.abs(v - 1.0))) <= 1e-6) continue;
        const a = ts[k - 1], b = ts[k];
        const where = ramp.smooth ? `smoothstep(${pyFloatRepr(a)}, ${pyFloatRepr(b)}, ${t})`
            : `clamp(((${t}) - ${pyFloatRepr(a)}) / ${pyFloatRepr(b - a)}, 0, 1)`;
        out.push({ scale_m: null, tint: ratio, amount: 1.0, where, from_ramp: tag });
    }
    return out;
}

/** A layer's `ramp` as the patches that draw it, relative to the layer's `colour` for a ramp of colours and to 1 for
 * a ramp of multipliers. [] without a ramp. */
export function rampPatches(layer) {
    const r = layer.ramp;
    if (!r) return [];
    const kind = rampStops(r)[2];
    if (kind === 'colour' && !layer.colour) throw new ValueError(`layer ${pyReprValue(layer.name ?? '?')}: a ramp of colours needs the layer's colour (its centre)`);
    return rampSegments(r, kind === 'colour' ? hexLinear(layer.colour) : [1.0, 1.0, 1.0], 'ramp');
}

/** options.satmap as the patches every layer takes. [] without a satmap. */
export function satmapPatches(pal) {
    const sm = (pal.options ?? {}).satmap;
    if (!sm) return [];
    const [ts, cs0, kind] = rampStops(sm);
    const amount = Number(sm.amount ?? 1.0);
    let cs = cs0;
    if (kind === 'colour') {
        const mid = rampValue(sm, 0.5);
        cs = cs.map((c) => c.map((v, k) => v / Math.max(mid[k], 1e-4)));
    }
    cs = cs.map((c) => c.map((v) => 1.0 + amount * (v - 1.0)));
    return rampSegments({ ...sm, stops: ts.map((t, k) => [t, cs[k]]) }, [1.0, 1.0, 1.0], 'satmap');
}

/** The palette's ramps as the rows of a ramp image: [rows (Float32Array of R x width x 4, sRGB-encoded 0..1, alpha
 * 1), index ({ key: { row, kind, gain, t, smooth } }: a layer's name for its ramp, 'satmap' for the options')]. */
export function rampRows(pal, width = 256) {
    pal = (!isObj(pal) || !('options' in pal)) ? get(pal) : pal;
    width = Math.trunc(width);
    // np.linspace(0, 1, width): arange(width) * (1 / (width - 1)), the last exactly 1
    const step = 1.0 / (width - 1);
    const tt = Array.from({ length: width }, (_, j) => (j === width - 1 ? 1.0 : j * step));
    const rows = [], index = {};
    const add = (key, ramp, lin, kind) => {
        const gain = kind === 'tint' ? Math.max(1.0, Math.max(...lin.flat())) : 1.0;
        const row = new Float32Array(width * 4);
        for (let j = 0; j < width; j++) {
            for (let c = 0; c < 3; c++) row[4 * j + c] = linearToSrgb(Math.min(Math.max(lin[j][c] / gain, 0.0), 1.0));
            row[4 * j + 3] = 1.0;
        }
        index[key] = { row: rows.length, kind, gain, t: String(ramp.t), smooth: Boolean(ramp.smooth) };
        rows.push(row);
    };
    for (const L of pal.layers) if (L.ramp) add(L.name, L.ramp, tt.map((t) => rampValue(L.ramp, t)), rampStops(L.ramp)[2]);
    const sm = pal.options.satmap;
    if (sm) {
        let lin = tt.map((t) => rampValue(sm, t));
        if (rampStops(sm)[2] === 'colour') {
            const mid = rampValue(sm, 0.5);
            lin = lin.map((c) => c.map((v, k) => v / Math.max(mid[k], 1e-4)));
        }
        const amount = Number(sm.amount ?? 1.0);
        add('satmap', sm, lin.map((c) => c.map((v) => 1.0 + amount * (v - 1.0))), 'tint');
    }
    const out = new Float32Array(rows.length * width * 4);
    rows.forEach((r, k) => out.set(r, k * width * 4));
    return [out, index];
}


