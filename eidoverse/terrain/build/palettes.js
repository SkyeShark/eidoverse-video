// Port of blender/eidoblend/terrain/build/palettes.py at ab3d5c3 (unchanged through d67f19e).
//
// The terrain's palettes (design section 7): which CC0 scans cover which ground, as data, plus the small mask
// expression language their layer weights and rock densities are written in. palettes.py's module doc is the guide
// to every key (a palette, its layers, options, strata, constants, dressing, the looks, the ramps, the language).
//
//     import * as P from './build/palettes.js';
//     P.names()                          // ['alpine', 'badlands', 'chalk_coast', 'desert_sandstone', 'dunes', ...]
//     const pal = P.get('alpine');       // a validated deep copy, every default filled in
//     P.get('auto', 'canyon')            // the recipe's palette (RECIPE_PALETTES, RECIPE_LOOKS); a recipe or its name
//     const [pal2, place] = P.forPlace('grand_canyon_toroweap')   // a real DEM's palette, strata, mask parameters
//     P.masksUsed(pal)                   // Set {'slope', 'talus', 'convex_20m', ...}
//     P.rampRows(pal)                    // [rows (Float32Array, R x 256 x 4, sRGB), { key: { row, kind, gain, t, smooth } }]
//     P.parse('smoothstep(30, 45, slope)')   // the expression tree surface/mask_expr.js compiles
//
// The data (the tables between the markers below) is palettes.py's module-level values as palettes.py builds them
// (its _cliff, _talus, _face and _debris templates and the looks' string sums evaluated), written by
// tests/surface_data/palettes_port.py under Blender's Python from the commit named above: tuples are arrays, None
// null. palettes.py's comments say why each value is what it is; read them there (this port does not tune looks:
// PORT_PLAN.md 3.5). tests/surface_data/palettes_test.mjs holds every table and every function's result JSON-equal to
// palettes.py's (get of every palette and of 'auto' for every recipe, check, the ramps' rows, forPlace, knownMask,
// parse, climateSun, columnLayers).
//
// Where this differs from palettes.py, and why:
//   - evaluate() (palettes.py's numpy evaluation over whole arrays) is per point here: numbers or a function of a
//     name, as the per-query reads take it (PORT_PLAN.md 2.4); over a level's texels the language runs on the GPU,
//     surface/mask_expr.js compiling a tree into a kernel. Its noise() and fbm() are valueNoise() and cells()
//     voronoiCells(), palettes.py's scatter noise, per point.
//   - The templates (_cliff, _talus, _face, _debris, _has) format numbers as JavaScript writes them: an integer as
//     Python writes an int (36), so the callers that pass the integers palettes.py's callers pass get its strings.
//   - Names are the edition's camelCase, with palettes.py's own beside them (get, check, parse, ...; known_mask and
//     knownMask), so a port of a Blender caller reads either.

