export const srgbToLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
export const linearToSrgb = (c) => {
    c = Math.max(c, 0.0);
    return c <= 0.0031308 ? c * 12.92 : 1.055 * c ** (1 / 2.4) - 0.055;
};
const HEX = /^#?([0-9a-fA-F]{6})$/;

/** '#rrggbb' (sRGB) -> linear [r, g, b]. */
export function hexLinear(h) {
    const m = HEX.exec(String(h).trim());
    if (!m) throw new ValueError(`colour ${pyReprValue(h)}: write it as sRGB "#rrggbb"`);
    const v = parseInt(m[1], 16);
    return [(v >> 16) & 255, (v >> 8) & 255, v & 255].map((c) => srgbToLinear(c / 255.0));
}


