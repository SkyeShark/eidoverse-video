/** [azimuth_deg, elevation_deg]: the place's climatological sun (palettes.py climate_sun): the bake (snowpack melt),
 * the plant layer and the material's insolation all read it. constants: any object (CONSTANTS fills what it lacks).
 * One that sets sun_azimuth_deg and sun_elevation_deg gets those (one alone is taken with the other from the
 * latitude); else the equinox noon sun of latitude_deg: due south (180) north of the equator, due north (0) south of
 * it, at 90 - |latitude| degrees. */
export function climateSun(constants = null) {
    const c = constants ?? {};
    let lat = Number(c.latitude_deg !== undefined && c.latitude_deg !== null ? c.latitude_deg : CONSTANTS.latitude_deg);
    lat = Math.max(-90.0, Math.min(90.0, lat));
    let az = lat >= 0.0 ? 180.0 : 0.0;
    let el = 90.0 - Math.abs(lat);
    if (c.sun_azimuth_deg !== undefined && c.sun_azimuth_deg !== null) az = pyMod(Number(c.sun_azimuth_deg), 360.0);
    if (c.sun_elevation_deg !== undefined && c.sun_elevation_deg !== null) el = Math.max(-90.0, Math.min(90.0, Number(c.sun_elevation_deg)));
    return [az, el];
}

// Python's float %: the sign of the divisor
function pyMod(a, b) {
    const r = a % b;
    return r !== 0 && (r < 0) !== (b < 0) ? r + b : r;
}


// ------------------------------------------------------------------------------ the expression language ---

export class ExprError extends ValueError {}

// a tokenizer and a precedence parser for the language's grammar, giving the tree palettes.py's ast walk gives
const TOKEN = /\s*(?:(\d+\.\d*(?:[eE][+-]?\d+)?|\.\d+(?:[eE][+-]?\d+)?|\d+(?:[eE][+-]?\d+)?)|([A-Za-z_]\w*)|(\*\*|[-+*/(),%]))/y;

function tokens(src) {
    const out = [];
    TOKEN.lastIndex = 0;
    const s = String(src).trim();
    while (TOKEN.lastIndex < s.length) {
        const at = TOKEN.lastIndex;
        const m = TOKEN.exec(s);
        if (!m) {
            const rest = s.slice(at).trimStart();
            if (!rest) break;
            throw new ExprError(`mask expression ${pyReprValue(src)}: invalid syntax at ${pyReprValue(rest.slice(0, 12))}`);
        }
        if (m[1] !== undefined) out.push(['num', parseFloat(m[1])]);
        else if (m[2] !== undefined) out.push(['name', m[2]]);
        else out.push(['op', m[3]]);
    }
    return out;
}

/** A mask expression -> a tree: ['num', v] | ['mask', name] | ['const', name] | ['op', '+-* /', a, b] |
 * ['neg', a] | ['call', fname, [args]] (palettes.py parse, its tuples as arrays). Throws ExprError naming what it
 * cannot read. */
export function parse(src) {
    if (typeof src === 'number') return ['num', Number(src)];
    const tk = tokens(src);
    let k = 0;
    const peek = () => tk[k];
    const take = (op) => {
        const t = tk[k];
        if (!t || t[0] !== 'op' || t[1] !== op) throw new ExprError(`mask expression ${pyReprValue(src)}: '${op}' expected`);
        k++;
    };
    const unsupported = (what) => new ExprError(`mask expression ${pyReprValue(src)}: ${what} is not part of the language ` +
        `(numbers, mask names, + - * /, and ${Object.keys(_FUNCS).sort().join(', ')})`);
    // the grammar of Python's expressions restricted to the language: sums of products of unary terms
    const expr = () => {
        let a = term();
        while (peek() && peek()[0] === 'op' && (peek()[1] === '+' || peek()[1] === '-')) {
            const op = tk[k++][1];
            a = ['op', op, a, term()];
        }
        return a;
    };
    const term = () => {
        let a = unary();
        while (peek() && peek()[0] === 'op' && (peek()[1] === '*' || peek()[1] === '/')) {
            const op = tk[k++][1];
            a = ['op', op, a, unary()];
        }
        if (peek() && peek()[0] === 'op' && (peek()[1] === '%' || peek()[1] === '**')) throw unsupported(`'${peek()[1]}'`);
        return a;
    };
    const unary = () => {
        const t = peek();
        if (t && t[0] === 'op' && (t[1] === '-' || t[1] === '+')) {
            k++;
            const a = unary();
            if (t[1] === '+') return a;
            return a[0] === 'num' ? ['num', -a[1]] : ['neg', a];
        }
        return atom();
    };
    const atom = () => {
        const t = tk[k++];
        if (!t) throw new ExprError(`mask expression ${pyReprValue(src)}: unexpected end`);
        if (t[0] === 'num') return ['num', t[1]];
        if (t[0] === 'op' && t[1] === '(') {
            const a = expr();
            take(')');
            return a;
        }
        if (t[0] === 'name') {
            const id = t[1];
            if (peek() && peek()[0] === 'op' && peek()[1] === '(') {
                k++;
                if (!(id in _FUNCS)) {
                    throw new ExprError(`mask expression ${pyReprValue(src)}: unknown function ${pyReprValue(id)}; the functions are ` +
                        Object.keys(_FUNCS).sort().join(', '));
                }
                const args = [];
                if (!(peek() && peek()[0] === 'op' && peek()[1] === ')')) {
                    args.push(expr());
                    while (peek() && peek()[0] === 'op' && peek()[1] === ',') {
                        k++;
                        args.push(expr());
                    }
                }
                take(')');
                const [lo, hi] = _FUNCS[id];
                if (!(lo <= args.length && args.length <= hi)) {
                    throw new ExprError(`mask expression ${pyReprValue(src)}: ${id}() takes ${lo}` + (hi !== lo ? `-${hi}` : '') +
                        ` arguments, got ${args.length}`);
                }
                if (['noise', 'fbm', 'cells'].includes(id) && args.some((a) => a[0] !== 'num')) {
                    throw new ExprError(`mask expression ${pyReprValue(src)}: ${id}(scale_m[, seed]) takes numbers`);
                }
                return ['call', id, args];
            }
            if (id in DERIVED) return parse(DERIVED[id]);
            if (id in CONSTANTS) return ['const', id];
            return ['mask', id];
        }
        throw unsupported(`'${t[1]}'`);
    };
    const tree = expr();
    if (k !== tk.length) throw new ExprError(`mask expression ${pyReprValue(src)}: invalid syntax`);
    return tree;
}

/** A key of an expression tree (its JSON): the material shares the nodes of equal sub-expressions. */
export function treeKey(t) {
    return JSON.stringify(t);
}

/** The mask names an expression (string or tree) reads (constants are not masks): a Set. */
export function namesIn(expr) {
    const t = Array.isArray(expr) ? expr : parse(expr);
    const out = new Set();
    const walk = (n) => {
        if (n[0] === 'mask') out.add(n[1]);
        else if (n[0] === 'op') { walk(n[2]); walk(n[3]); }
        else if (n[0] === 'neg') walk(n[1]);
        else if (n[0] === 'call') for (const a of n[2]) walk(a);
    };
    walk(t);
    return out;
}

