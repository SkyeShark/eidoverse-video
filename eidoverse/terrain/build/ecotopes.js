// Port of blender/eidoblend/terrain/build/ecotopes.py at f9fba8c.
//
// The terrain's ecotopes (SURFACING_DESIGN.md 4.2): which plants a kind of place grows and where, as data. An
// ecotope is a list of species, each with a density written in the palettes' mask expression language
// (build/palettes.js), so a plant rule reads the same terrain data a material layer does. build/plants.js turns an
// ecotope into spots, and build/plant_instances.js instances the spots in a three.js scene.
//
//     import * as E from './build/ecotopes.js';
//     E.names()                                  // ['alpine', 'badlands', 'chalk_coast', 'desert_sandstone', ...]
//     const eco = E.get('alpine');               // a validated deep copy, every default filled in
//     E.get('auto', 'fluvial_range')             // the recipe's palette's ecotope with its RECIPE_ECOTOPES
//     E.get('auto', realPlaceRecipe, 'lauterbrunnen', 'alpine')   // a real place's (PLACE_ECOTOPES)
//     E.describe('alpine')                       // one page: species, sources, densities, sizes
//     E.ecotopeHash(eco)                         // what the spots' file names the ecotope by (Blender's, to the bit)
//
// ecotopes.py's module doc is the guide to every key of an ecotope and of a species (name, kind, source, density,
// size_m, stature, age, cluster, core_m, crown_m, foot_m, priority, shade, casts_shade, around, ground, max_radius_m,
// max_cell_m, lod_m_per_m, fade, max_count, lod, align, sink, on, roots_m, range_per_ha), to the density language's
// derived names (site, slope_20m, northness_20m, eastness_20m, soil, insolation, dist_channel, dist_water,
// fall_streak, shade, ledge: build/plants.js DERIVED_NAMES) and to how the rules are written; its comments say why
// each value is what it is. Read them there: this port does not tune plants (PORT_PLAN.md 3.5).
//
// The data (the block between the markers below) is ecotopes.py's module-level values as ecotopes.py builds them
// (its sources and the treeline templates evaluated into the density strings), written by
// tests/plants/ecotopes_port.py under Blender's Python from the commit named above: tuples are arrays, None null.
// tests/plants/ecotopes_test.mjs holds every ecotope, every recipe's and every place's 'auto' resolution, check(),
// describe(), masksUsed() and the hashes JSON-equal to ecotopes.py's.
//
// Where this differs from ecotopes.py, and why:
//   - The data block is generated, not written by hand (palettes.js's rule, P14): the density strings are sums of
//     ecotopes.py's templates, and a hand copy could drift from them.
//   - A source is the array [kind, id, options, seeds] where ecotopes.py has a tuple.
//   - ecotopeHash(eco) needs Python's json.dumps(sort_keys=True) text, which tells an int from a float: JavaScript has
//     one number type, so pyJsonSorted writes an integral number as an int under the keys that hold Python ints in
//     ecotopes.py's data (INT_KEYS: priority, max_count, a source's seeds and SeedThree's integer dials) and as a
//     float's repr everywhere else (every rate, size and radius). tests/plants/ecotopes_test.mjs checks the text and
//     the hash of every built-in resolution against Python's.
//   - Names are the edition's camelCase, with ecotopes.py's own beside them (get, check, describe, ecotopeHash and
//     ecotope_hash, masksUsed and masks_used, resolveName and resolve_name, sourceDict and source_dict).

