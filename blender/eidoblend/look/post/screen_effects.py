WIRE_PALETTES = {'green': (0.000, 0.667, 0.000), 'amber': (1.000, 0.690, 0.000), 'blue': (0.082, 0.051, 0.969)}
WIRE_MULTI = [(1.0, 0.20, 0.20), (0.20, 1.0, 0.30), (0.30, 0.50, 1.0), (1.0, 1.0, 0.20), (0.30, 1.0, 1.0),
              (1.0, 0.30, 1.0), (1.0, 0.60, 0.10), (1.0, 1.0, 1.0)]


def _wire_material(line_width, bg, line_color, intensity, cap, multi):
    """retro_wireframe.js's wire material: every triangle edge a line of constant pixel width (the Wireframe node in
    pixel size: render triangles, as WebGPU's barycentrics), the line colour pushed to `line_intensity` luminance and
    capped per channel, the background colour between. Emission only (unlit, as its outputNode)."""
    import bpy
    m = bpy.data.materials.get('retro_wireframe') or bpy.data.materials.new('retro_wireframe')
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    N, L = nt.nodes, nt.links

    def val(name, v):
        n = N.new('ShaderNodeValue')
        n.name = n.label = name
        n.outputs[0].default_value = v
        return n.outputs[0]

    def rgb(name, c):
        n = N.new('ShaderNodeRGB')
        n.name = n.label = name
        n.outputs[0].default_value = (*c, 1.0)
        return n.outputs[0]

    def vmath(op, a, b=None, scale=None):
        n = N.new('ShaderNodeVectorMath')
        n.operation = op
        L.new(a, n.inputs[0])
        if b is not None:
            L.new(b, n.inputs[1])
        if scale is not None:
            L.new(scale, n.inputs['Scale'])
        return n.outputs['Value'] if op == 'DOT_PRODUCT' else n.outputs['Vector']

    def math(op, a, b):
        n = N.new('ShaderNodeMath')
        n.operation = op
        for i, x in enumerate((a, b)):
            if isinstance(x, (int, float)):
                n.inputs[i].default_value = x
            else:
                L.new(x, n.inputs[i])
        return n.outputs[0]
    wire = N.new('ShaderNodeWireframe')
    wire.use_pixel_size = True
    lw = val('line_width', line_width)
    L.new(lw, wire.inputs['Size'])
    lc, bgc = rgb('line_color', line_color), rgb('bg_color', bg)
    inten, capv, is_multi = val('line_intensity', intensity), val('hdr_channel_cap', cap), val('is_multi_color', multi)
    lum_w = N.new('ShaderNodeCombineXYZ')
    lum_w.inputs[0].default_value, lum_w.inputs[1].default_value, lum_w.inputs[2].default_value = 0.2126, 0.7152, 0.0722
    single = vmath('SCALE', lc, scale=math('DIVIDE', inten, math('MAXIMUM', vmath('DOT_PRODUCT', lc, lum_w.outputs[0]),
                                                                     0.01)))
    # multicolor: a palette pick per triangle from the tri_hash face attribute (retro_wireframe's GN modifier)
    attr = N.new('ShaderNodeAttribute')
    attr.attribute_name = 'tri_hash'
    idx = math('MINIMUM', math('MAXIMUM', math('FLOOR', math('MULTIPLY', attr.outputs['Fac'], 8.0), 0.0), 0.0), 7.0)
    pick = rgb('multi0', WIRE_MULTI[0])
    for i in range(1, 8):
        mx = N.new('ShaderNodeMix')
        mx.data_type = 'RGBA'
        L.new(math('GREATER_THAN', idx, i - 0.5), mx.inputs['Factor'])
        L.new(pick, mx.inputs[6])
        L.new(rgb(f'multi{i}', WIRE_MULTI[i]), mx.inputs[7])
        pick = mx.outputs[2]
    multi_c = vmath('SCALE', pick, scale=math('DIVIDE', inten, math('MAXIMUM', vmath('DOT_PRODUCT', pick,
                                                                                    lum_w.outputs[0]), 0.01)))
    mixm = N.new('ShaderNodeMix')
    mixm.data_type = 'VECTOR'
    L.new(is_multi, mixm.inputs['Factor'])
    L.new(single, mixm.inputs[4])
    L.new(multi_c, mixm.inputs[5])
    capvec = N.new('ShaderNodeCombineXYZ')
    for k in range(3):
        L.new(capv, capvec.inputs[k])
    hdr = vmath('MINIMUM', mixm.outputs[1], capvec.outputs[0])
    fin = N.new('ShaderNodeMix')
    fin.data_type = 'RGBA'
    L.new(wire.outputs['Fac'], fin.inputs['Factor'])
    L.new(bgc, fin.inputs[6])
    L.new(hdr, fin.inputs[7])
    em = N.new('ShaderNodeEmission')
    L.new(fin.outputs[2], em.inputs['Color'])
    em.inputs['Strength'].default_value = 1.0
    out = N.new('ShaderNodeOutputMaterial')
    L.new(em.outputs['Emission'], out.inputs['Surface'])
    return m


def _tri_hash_group():
    """A Geometry Nodes group triangulating a mesh and storing tri_hash = ((t x 2654435761) mod 0xffffffff) /
    0xffffffff per triangle (retro_wireframe.js's per-triangle hash), for multicolor."""
    import bpy
    ng = bpy.data.node_groups.get('retro_wireframe_tri_hash')
    if ng is not None:
        return ng
    ng = bpy.data.node_groups.new('retro_wireframe_tri_hash', 'GeometryNodeTree')
    ng.interface.new_socket(name='Geometry', in_out='INPUT', socket_type='NodeSocketGeometry')
    ng.interface.new_socket(name='Geometry', in_out='OUTPUT', socket_type='NodeSocketGeometry')
    N, L = ng.nodes, ng.links
    gi, go = N.new('NodeGroupInput'), N.new('NodeGroupOutput')
    tri = N.new('GeometryNodeTriangulate')
    L.new(gi.outputs[0], tri.inputs['Mesh'])
    index = N.new('GeometryNodeInputIndex')
    # the hash in Geometry Nodes' float32 maths: t x 2654435761 mod 4294967295 is NOT exact there (24-bit
    # mantissa; the JS ran it in doubles), it is about fract(t x 0.618034) (2654435761 / 2^32 is the golden ratio's
    # conjugate), so it still spreads the palette evenly, on other triangles than WebGPU's
    m1 = N.new('ShaderNodeMath')
    m1.operation = 'MULTIPLY'
    L.new(index.outputs[0], m1.inputs[0])
    m1.inputs[1].default_value = 2654435761.0
    m2 = N.new('ShaderNodeMath')
    m2.operation = 'FLOORED_MODULO'
    L.new(m1.outputs[0], m2.inputs[0])
    m2.inputs[1].default_value = 4294967295.0
    m3 = N.new('ShaderNodeMath')
    m3.operation = 'DIVIDE'
    L.new(m2.outputs[0], m3.inputs[0])
    m3.inputs[1].default_value = 4294967295.0
    st = N.new('GeometryNodeStoreNamedAttribute')
    st.data_type = 'FLOAT'
    st.domain = 'FACE'
    st.inputs['Name'].default_value = 'tri_hash'
    L.new(tri.outputs['Mesh'], st.inputs['Geometry'])
    L.new(m3.outputs[0], st.inputs['Value'])
    L.new(st.outputs['Geometry'], go.inputs[0])
    return ng


def retro_wireframe(scene, o):
    """retro_wireframe.js: every mesh drawn as its triangle wireframe (a view-layer material override), the world the
    background colour; color 'green' | 'amber' | 'blue' | 'multicolor' (a palette pick per triangle: a Geometry
    Nodes modifier stores the hash). Returns (material, {uniform: node socket}); cleanup with
    retro_wireframe_cleanup(scene)."""
    import bpy
    color = o.get('color', 'green')
    if color not in WIRE_PALETTES and color != 'multicolor':
        raise ValueError(f"retro_wireframe: unknown color {color!r}. Valid: {', '.join(WIRE_PALETTES)}, multicolor")
    bg = tuple(o.get('bg_color', (0.0, 0.0, 0.0)))
    m = _wire_material(float(o.get('line_width', 1.5)), bg, WIRE_PALETTES.get(color, (0.0, 1.0, 0.0)),
                       float(o.get('line_intensity', 1.0)), float(o.get('hdr_channel_cap', 6.3)),
                       1.0 if color == 'multicolor' else 0.0)
    vl = bpy.context.view_layer if bpy.context.scene == scene else scene.view_layers[0]
    if 'retro_wireframe_prev_override' not in scene:          # a second apply keeps the state before the first
        prev = vl.material_override
        scene['retro_wireframe_prev_override'] = prev.name if (prev is not None and prev != m) else ''
    vl.material_override = m
    if color == 'multicolor':
        ng = _tri_hash_group()
        for ob in scene.objects:
            if ob.type == 'MESH' and 'retro_wireframe_tris' not in ob.modifiers:
                mod = ob.modifiers.new('retro_wireframe_tris', 'NODES')
                mod.node_group = ng
    # scene.background = bgColor: a world of its own as the view layer's world override, so a sky whose colour is
    # linked (a texture, the sky family's world) is replaced too, and the scene's world is never edited
    w = _wire_world(bg)
    if 'retro_wireframe_prev_world' not in scene:
        prev_w = vl.world_override
        scene['retro_wireframe_prev_world'] = prev_w.name if (prev_w is not None and prev_w != w) else ''
    vl.world_override = w
    nodes = m.node_tree.nodes
    U = {'line_color': nodes['line_color'].outputs[0], 'bg_color': nodes['bg_color'].outputs[0],
         'line_width': nodes['line_width'].outputs[0], 'line_intensity': nodes['line_intensity'].outputs[0],
         'hdr_channel_cap': nodes['hdr_channel_cap'].outputs[0], 'is_multi_color': nodes['is_multi_color'].outputs[0],
         'background': w.node_tree.nodes['retro_wireframe_bg'].inputs['Color']}
    for i in range(8):
        U[f'multi{i}'] = nodes[f'multi{i}'].outputs[0]
    return m, U


def _wire_world(bg):
    """The background world: bgColor, unlit by anything else (the override material is emission only)."""
    import bpy
    w = bpy.data.worlds.get('retro_wireframe_bg') or bpy.data.worlds.new('retro_wireframe_bg')
    w.use_nodes = True
    nt = w.node_tree
    nt.nodes.clear()
    b = nt.nodes.new('ShaderNodeBackground')
    b.name = 'retro_wireframe_bg'
    b.inputs['Color'].default_value = (*bg, 1.0)
    b.inputs['Strength'].default_value = 1.0
    o = nt.nodes.new('ShaderNodeOutputWorld')
    nt.links.new(b.outputs['Background'], o.inputs['Surface'])
    return w


def set_wire_color(scene, U, name):
    """retro_wireframe's setColor(name): a palette, or 'multicolor' (adds the per-triangle hash modifiers)."""
    if name == 'multicolor':
        U['is_multi_color'].default_value = 1.0
        ng = _tri_hash_group()
        for ob in scene.objects:
            if ob.type == 'MESH' and 'retro_wireframe_tris' not in ob.modifiers:
                ob.modifiers.new('retro_wireframe_tris', 'NODES').node_group = ng
    elif name in WIRE_PALETTES:
        U['line_color'].default_value = (*WIRE_PALETTES[name], 1.0)
        U['is_multi_color'].default_value = 0.0
    else:
        raise ValueError(f'retro_wireframe: unknown color {name!r}')


def retro_wireframe_cleanup(scene):
    """retro_wireframe's cleanup(): the materials, meshes and background back as they were."""
    import bpy
    vl = bpy.context.view_layer if bpy.context.scene == scene else scene.view_layers[0]
    prev = scene.get('retro_wireframe_prev_override', '')
    vl.material_override = bpy.data.materials.get(prev) if prev else None
    for ob in scene.objects:
        mod = ob.modifiers.get('retro_wireframe_tris') if ob.type == 'MESH' else None
        if mod is not None:
            ob.modifiers.remove(mod)
    if 'retro_wireframe_prev_world' in scene:
        pw = scene['retro_wireframe_prev_world']
        vl.world_override = bpy.data.worlds.get(pw) if pw else None
    w = bpy.data.worlds.get('retro_wireframe_bg')
    if w is not None and w.users == 0:
        bpy.data.worlds.remove(w)
    for k in ('retro_wireframe_prev_override', 'retro_wireframe_prev_world'):
        if k in scene:
            del scene[k]


