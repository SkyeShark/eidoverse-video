def hatch_noise():
    """cross_hatch.js's 256 x 256 RGBA noise texture: its LCG run with JavaScript's double-precision multiply and
    ToInt32 (checked against deno: the same first bytes and checksum), stored flipped so a y-down tap reads its rows
    as the WebGPU DataTexture did, packed in the file. Red, green and blue are its bytes; alpha is held at 1: the
    shader never reads the fourth channel, and the compositor's Image node premultiplies colour by alpha whatever
    the image's alpha mode (measured 11-08: the noise came out at half its mean, every hatch layer darker)."""
    import bpy
    import numpy as np
    name = 'eido_cross_hatch_noise'
    im = bpy.data.images.get(name)
    if im is not None and im.get('eido_lcg') == 2:
        return im
    n = 256 * 256 * 4
    data = np.empty(n, np.uint8)
    s = 0x12345678
    for i in range(n):
        x = int(float(s) * 1103515245.0 + 12345.0) % (1 << 32)          # (s * 1103515245 + 12345) | 0
        s = x - (1 << 32) if x >= (1 << 31) else x
        data[i] = (x >> 16) & 0xff                                      # (s >>> 16) & 0xff
    px = data.reshape(256, 256, 4)[::-1].astype(np.float32) / 255.0
    px[..., 3] = 1.0
    if im is None:
        im = bpy.data.images.new(name, 256, 256, alpha=True, float_buffer=False)
    im.colorspace_settings.name = 'Non-Color'
    im.alpha_mode = 'STRAIGHT'
    im.pixels.foreach_set(px.ravel())
    im.pack()
    im['eido_lcg'] = 2
    im.use_fake_user = True
    return im


def _hatch_rand(g, nz, px_, py_):
    """getRand(pos): the noise texture at uvSmooth(pos / 256, 256), wrapped (RepeatWrapping, linear). uvSmooth(uv, res)
    = uv + 0.6 sin(uv res 2 pi) / 2 pi / res: one period per texel (uv res = pos), so the bilinear ramp between texel
    centres turns S-shaped, the anti-banding of the shader's noise texture."""
    u, v = px_ / 256.0, py_ / 256.0
    u = u + g.sin(px_ * TAU) * (0.6 / TAU / 256.0)
    v = v + g.sin(py_ * TAU) * (0.6 / TAU / 256.0)
    return g.tap(nz, g.vec(u, v), ext='Repeat')


def _hatch_val_fn():
    """getVal(pos, ramp, rsc, sc): the frame at pos wiggled by the noise, tone-mapped c / (c + 1), averaged."""
    def body(g, a):
        img = a['Image']
        co = g.coords(img)
        nn = g.node('CompositorNodeImage')
        nn.image = hatch_noise()
        nz = nn.outputs['Image']
        pos, ramp, rsc, sc, t = a['pos'], a['ramp'], a['rsc'], a['sc'], a['time']
        off = t * 131.0 * a['flicker']
        rr = _hatch_rand(g, nz, pos.x * 0.05 * rsc / sc + off, pos.y * 0.05 * rsc / sc + off)
        k = 10.0 * ramp * a['wiggle'] * sc
        c = g.tap(img, g.vec((pos.x + (rr.x - 0.5) * k) / co.W, (pos.y + (rr.y - 0.5) * k) / co.H))
        tm = c / (c + g.v((1.0, 1.0, 1.0)))
        return {'v': g.clamp(g.dot(tm, (0.333, 0.333, 0.333)), 0.0, 1.0)}
    ins = [('Image', 'C', (0, 0, 0, 1)), ('pos', 'V', (0.0, 0.0, 0.0)), ('ramp', 'S', 0.0), ('rsc', 'S', 1.0),
           ('sc', 'S', 1.0), ('time', 'S', 0.0), ('flicker', 'S', 1.0), ('wiggle', 'S', 1.0)]
    # version 2: uvSmooth's period is one texel (it was 256 texels); a file's older group is rebuilt
    return fn('fx_cross_hatch_val', ins, [('v', 'S')], body, version=2)


def cross_hatch_group():
    """cross_hatch.js: a pencil drawing. Outlines from the gradient of the noise-wiggled, tone-mapped frame at three
    scales plus depth edges; five layers of hatching whose density follows the frame's value (later layers skipped
    on bright pixels, as the shader's Break), turned 90 degrees on near objects; a facing-ratio boost from the view
    normals; paper grain, vignette and an S-curve. Its normal is decoded twice, as WebGPU's (|2 n.z - 1|)."""
    def body(g, a):
        img = a['Image']
        co = g.coords(img)
        t, _f = g.time()
        nn = g.node('CompositorNodeImage')
        nn.image = hatch_noise()
        nz = nn.outputs['Image']
        W, H = co.W, co.H
        fx, fy = co.fx, co.fy
        far, hasD, hasN = a['Far'], a['HasDepth'], a['HasNormal']
        sc = g.max(W / 600.0, 0.5)
        sq = g.sqrt(sc)
        rpx, rpy = fx * 1.2 / sq, fy * 1.2 / sq
        r2 = _hatch_rand(g, nz, rpx, rpy)
        r = r2 - _hatch_rand(g, nz, rpx + 1.5, rpy - 1.5)
        common = dict(Image=img, sc=sc, time=t, flicker=a['flicker'], wiggle=a['wiggle'])
        val = _hatch_val_fn()

        def get_val(px_, py_, ramp, rsc):
            return g.call(val, pos=g.vec(px_, py_), ramp=ramp, rsc=rsc, **common)['v']
        # depth edges (perspectiveDepthToViewZ: the metric view depth; far where nothing was drawn)
        dimg = g.image(a['Depth'])

        def z(x, y):
            return g.min(far, g.max(0.0, g.tap(dimg, g.vec(co.u + co.pxu * x, co.v + co.pxv * y)).x))
        dC = g.max(z(0, 0), 0.0001)
        centre = g.mix(far, dC, hasD)
        d = {(x, y): z(x, y) for x in (-1, 0, 1) for y in (-1, 0, 1) if (x, y) != (0, 0)}
        dDepth = (g.abs(d[(0, -1)] - d[(0, 1)]) + g.abs(d[(1, 0)] - d[(-1, 0)]) + g.abs(d[(-1, -1)] - d[(1, 1)])
                  + g.abs(d[(1, -1)] - d[(-1, 1)])) / dC
        th = a['depth_outline_thresh']
        depth_edge = g.smoothstep(th, th * 8.0, dDepth) * hasD
        # the outline: gradient lengths at three scales, two bands each
        br = 0.0
        for i in range(3):
            fi = i / 2.0
            tt = 0.03 + fi * 0.25
            wb = tt * 2.0
            for ramp, rsc, w0, w1 in ((0.15 * 1.3 ** (fi * 5), 1.7 * 1.3 ** (-fi * 5), 0.6, 0.5 + fi),
                                      (0.30 * 1.3 ** (fi * 5), 10.7 * 1.3 ** (-fi * 5), 0.4, 0.2 + fi)):
                eps = sc * 0.4
                gx = get_val(fx + eps, fy, ramp, rsc) - get_val(fx - eps, fy, ramp, rsc)
                gy = get_val(fx, fy + eps, ramp, rsc) - get_val(fx, fy - eps, ramp, rsc)
                glen = g.sqrt(gx * gx + gy * gy) / eps / 2.0 * sc
                br = br + g.smoothstep(tt - wb * 0.5, tt + wb * 0.5, glen) * (w0 * w1)
        grain = r2.z * 0.5 + 0.5
        colour_outline = br * a['outline_strength'] * 0.7 * grain
        depth_outline = depth_edge * a['depth_outline_strength'] * grain
        total = g.clamp(colour_outline + depth_outline, 0.0, 0.6)
        col = g.splat(g.clamp(1.0 - total, 0.0, 1.0))
        # the hatching: five layers, the later ones skipped where the jittered value is bright (the Break)
        rj = _hatch_rand(g, nz, fx * 0.02 + t * 1120.0, fy * 0.02 + t * 1120.0)
        jk = 1.5 * g.clamp(a['flicker'], -1.0, 1.0) * sc
        val_jit = get_val(fx + (rj.x - 0.5) * jk, fy + (rj.y - 0.5) * jk, 0.0, 1.0) * 1.7
        is_obj = (1.0 - g.smoothstep(far * 0.08, far * 0.18, centre)) * hasD
        hatch, hatch2, hsum, alive = 0.0, 0.0, 0.0, 1.0
        for i in range(5):
            fi = float(i)
            if i >= 2:
                alive = alive * (1.0 - g.math('GREATER_THAN', fi, (1.0 - val_jit) * 5.0))
            ang = (-0.5 - fi * fi * 0.08) + is_obj * (math.pi / 2.0)
            c0, c1 = g.cos(ang), g.cos(ang - 1.6)
            hx = (c0 * fx - c1 * fy) / sq * (0.05 * 1.3)
            hy = (c1 * fx + c0 * fy) / sq * 1.3
            drift = t * 1003.123 * a['flicker']
            rh = _hatch_rand(g, nz, hx + g.sin(hy) + drift, hy + drift)
            contrib = 1.0 - g.smoothstep(0.5, 1.5, rh.x + val_jit) - g.abs(r.z) * 0.3
            hatch = hatch + contrib * alive
            hatch2 = g.mix(hatch2, g.max(hatch2, contrib), alive)
            hsum = hsum + alive
        # facing ratio from the view normal: grazing faces hatch harder
        nimg = g.image(a['Normal'])
        nzv = g.dot(g.tap(nimg, co.uv), a['CamZ']) * 2.0 - 1.0
        boost = g.mix(1.2, 0.7, g.clamp(g.abs(nzv), 0.0, 1.0))
        is_geo = 1.0 - g.smoothstep(far * 0.85, far * 0.99, centre)
        shade = g.mix(1.0, g.mix(1.0, boost, is_geo), hasN * hasD)
        amount = g.clamp(g.mix(hatch / g.max(hsum, 0.0001), hatch2, 0.5) * a['hatch_strength'] * shade, 0.0, 1.0)
        col = col * (1.0 - amount)
        one = g.v((1.0, 1.0, 1.0))
        col = one - (one - col) * 0.92
        col = col * (g.splat(r.x * 0.06 + 0.95) + r * 0.06)
        sx, sy = (fx - W * 0.5) / W, (fy - H * 0.5) / W
        vign = (1.0 - (sx * sx + sy * sy) * 0.15) * (1.0 - g.exp(g.sin(co.u * math.pi) * -40.0) * 0.3) \
            * (1.0 - g.exp(g.sin(co.v * math.pi) * -20.0) * 0.3)
        col = col * vign
        col = g.mix(col, g.smoothstep((0.15, 0.15, 0.15), (0.85, 0.85, 0.85), col), 0.6)
        return {'Image': _mix4(g, img, g.clamp(col, 0.0, 1.0), 1.0, a['opacity'])}
    ins = _io(CROSS_HATCH) + [('Depth', 'S', 1.0), ('Normal', 'V', (0.0, 0.0, 1.0)), ('HasDepth', 'S', 0.0),
                              ('HasNormal', 'S', 0.0), ('Far', 'S', 100.0), ('CamX', 'V', (1.0, 0.0, 0.0)),
                              ('CamY', 'V', (0.0, 1.0, 0.0)), ('CamZ', 'V', (0.0, 0.0, 1.0))]
    # version 2: uvSmooth's period is one texel (it was 256 texels); a file's older group is rebuilt
    return fn('fx_cross_hatch', ins, [('Image', 'C')], body, version=2)


