UNDERWATER = [('opacity', 1.0), ('horizon_color', (0.0, 0.05, 0.2)), ('shallow_color', (0.18, 0.45, 0.55)),
              ('fog_density', 0.3), ('fog_power', 1.0), ('caustic_amt', 1.4), ('caustic_scale', 0.5),
              ('godray_amt', 0.6)]
_UW_COLOURS = ('horizon_color', 'shallow_color')


def _caustic2d_fn():
    """underwater.js caustic2D(uv, t): five rounds of the water-caustic iteration -> clamp(|1.17 - (c/5)^1.4|^8)."""
    def body(g, a):
        uv, t = a['uv'], a['t']
        ppx, ppy = g.mod(uv.x * TAU, TAU) - 250.0, g.mod(uv.y * TAU, TAU) - 250.0
        tt = t * 0.5 + 23.0
        ix, iy, c = ppx, ppy, 1.0
        for i in range(5):
            tn = tt * (1.0 - 3.5 / (i + 1))
            ix, iy = ppx + g.cos(tn - ix) + g.sin(tn + iy), ppy + g.sin(tn - iy) + g.cos(tn + ix)
            dx, dy = g.sin(ix + tn) / 0.005, g.cos(iy + tn) / 0.005
            qx, qy = ppx / dx, ppy / dy
            c = c + 1.0 / g.sqrt(qx * qx + qy * qy)
        cf = 1.17 - g.pow(c / 5.0, 1.4)
        return {'c': g.clamp(g.pow(g.abs(cf), 8.0), 0.0, 2.0)}
    return fn('fx_uw_caustic2d', [('uv', 'V', (0.0, 0.0, 0.0)), ('t', 'S', 0.0)], [('c', 'S')], body)


def _caustic1d(g, x, power, gt):
    """underwater.js caustic1D(x, power, t): two rounds -> 1.17 - (c/5)^power."""
    pp = g.mod(x * TAU, TAU) - 250.0
    tt = gt * 0.5 + 23.0
    ii, c = pp, 1.0
    for i in range(2):
        tn = tt * (1.0 - 3.5 / (i + 1))
        ii = pp + g.cos(tn - ii) + g.sin(tn + ii)
        c = c + 1.0 / g.abs(pp / (g.sin(ii + tn) / 0.005))
    return 1.17 - g.pow(c / 5.0, power)


def underwater_group():
    """underwater.js's screen pass: where nothing was drawn, a wispy water roof of caustics fading to the horizon
    colour; on geometry, caustics at the world position (on up-facing surfaces) and depth fog toward the horizon
    colour; screen-space god rays. The view position is rebuilt from the Depth pass along the pixel's ray (the
    camera's tan(fov / 2) and aspect), the world position through the camera's axes and position (drivers)."""
    def body(g, a):
        img = a['Image']
        co = g.coords(img)
        t, _f = g.time()
        base = g.c(img)
        dimg, nimg = g.image(a['Depth']), g.image(a['Normal'])
        far, near, hasD, hasN = a['Far'], a['Near'], a['HasDepth'], a['HasNormal']
        z = g.mix(far, g.min(far, g.max(near, g.tap(dimg, co.uv).x)), hasD)
        aspect = co.W / co.H
        vx = (co.u * 2.0 - 1.0) * a['TanY'] * aspect * z
        vy = (1.0 - co.v * 2.0) * a['TanY'] * z
        vz = -z
        dist = g.sqrt(vx * vx + vy * vy + vz * vz)
        world = a['CamPos'] + a['CamX'] * vx + a['CamY'] * vy + a['CamZ'] * vz       # Blender axes
        d01 = far * (z - near) / (z * (far - near))                    # the WebGPU depth buffer's value
        is_far = g.clamp((d01 - 0.999) * 1000.0, 0.0, 1.0)
        px_, py_ = co.u * 2.0 - 1.0, co.v * 2.0 - 1.0                  # p = uv * 2 - 1, y down as WebGPU's uv
        shallow, horizon = g.c(a['shallow_color']), g.c(a['horizon_color'])
        sky_mask = g.clamp(0.8 * (1.0 - (py_ + 0.8) * 2.5), 0.0, 1.0)
        cau = _caustic2d_fn()
        cs1 = g.call(cau, uv=g.vec(px_, py_), t=t)['c']
        cs2 = g.call(cau, uv=g.vec(px_, py_ * 2.7), t=t)['c']
        py4 = py_ * py_ * py_ * py_
        sky = g.mix(shallow * sky_mask + shallow * ((cs1 * 0.3 + cs2 * 0.3) * py4), horizon,
                    g.pow(1.0 - py4, 20.0))
        # three's world (x, y, z) is Blender's (x, z, -y): caustics on the three xz plane, leaning with height
        cin = g.vec(world.x + world.z * 0.2, -world.y + world.z * 0.2) * a['caustic_scale']
        cval = g.call(cau, uv=cin, t=t)['c']
        n_up = g.mix(1.0, g.clamp(g.dot(g.tap(nimg, co.uv), a['CamY']), 0.0, 1.0), hasN)   # view-space n.y
        fog = 1.0 - g.exp(-(g.pow(dist, a['fog_power']) * a['fog_density']))
        scene_c = base * (cval * a['caustic_amt'] * n_up + 0.7)
        out = g.mix(g.mix(scene_c, horizon, fog), sky, is_far)
        gr1 = g.pow(g.abs(_caustic1d(g, (px_ + py_ * 0.08) / 1.7 + 0.5, 1.8, t * 0.65)), 10.0) * 0.05
        c2 = _caustic1d(g, g.sin(px_), 0.3, t * 0.7)
        gr2 = g.sign(c2) * g.pow(g.abs(c2), 9.0) * 0.4
        gr3 = g.pow(g.abs(_caustic1d(g, g.cos(px_ * 2.3), 0.3, t * 1.3)), 4.0) * 0.1
        f1 = g.pow((1.0 + py_) * 0.3, 2.0) * 0.2
        f2 = g.pow((1.0 + py_) * 0.3, 3.0)
        rays = g.clamp(gr1 + gr2 + gr3 - f1 - f2, 0.0, 1.0) * a['godray_amt']
        out = out + g.v((0.7, 1.0, 1.0)) * (rays * g.mix(g.length(shallow), 1.0, py_ * py_))
        return {'Image': _mix4(g, img, out, g.alpha(img), a['opacity'])}
    ins = _io(UNDERWATER, colour=_UW_COLOURS) + [
        ('Depth', 'S', 1.0), ('Normal', 'V', (0.0, 0.0, 1.0)), ('HasDepth', 'S', 0.0), ('HasNormal', 'S', 0.0),
        ('Far', 'S', 100.0), ('Near', 'S', 0.1), ('TanY', 'S', 0.414), ('CamPos', 'V', (0.0, 0.0, 0.0)),
        ('CamX', 'V', (1.0, 0.0, 0.0)), ('CamY', 'V', (0.0, 1.0, 0.0)), ('CamZ', 'V', (0.0, 0.0, 1.0))]
    return fn('fx_underwater', ins, [('Image', 'C')], body)


def _drive(sock, scene, path, expr='v', index=-1):
    try:
        sock.driver_remove('default_value', index)
    except (TypeError, RuntimeError):
        pass
    fc = sock.driver_add('default_value', index) if index >= 0 else sock.driver_add('default_value')
    d = fc.driver
    d.type = 'SCRIPTED'
    v = d.variables.new()
    v.name = 'v'
    v.type = 'SINGLE_PROP'
    v.targets[0].id_type = 'SCENE'
    v.targets[0].id = scene
    v.targets[0].data_path = path
    d.expression = expr
    return fc


def drive_tan_half_fov_y(scene, sock):
    """A driver keeping `sock` at tan(vertical fov / 2) of the scene camera AS IT RENDERS THE FRAME: the sensor fit
    (AUTO: the sensor width spans the frame's longer side; HORIZONTAL; VERTICAL: the sensor height), the lens and the
    frame's aspect (pixel aspect included). camera.data.angle_y is NOT that: it is always the sensor height's angle,
    18.5 % too wide for a 16:9 frame on an AUTO-fit camera. A simple expression (no Python), so a saved .blend
    evaluates it with scripts off."""
    try:
        sock.driver_remove('default_value')
    except (TypeError, RuntimeError):
        pass
    fc = sock.driver_add('default_value')
    d = fc.driver
    d.type = 'SCRIPTED'
    for name, path in (('lens', 'camera.data.lens'), ('sw', 'camera.data.sensor_width'),
                       ('sh', 'camera.data.sensor_height'), ('fit', 'camera.data.sensor_fit'),
                       ('rx', 'render.resolution_x'), ('ry', 'render.resolution_y'),
                       ('ax', 'render.pixel_aspect_x'), ('ay', 'render.pixel_aspect_y')):
        v = d.variables.new()
        v.name = name
        v.type = 'SINGLE_PROP'
        v.targets[0].id_type = 'SCENE'
        v.targets[0].id = scene
        v.targets[0].data_path = path
    # fit: 0 AUTO, 1 HORIZONTAL, 2 VERTICAL (the enum's values)
    d.expression = ('sh / (2 * lens) if fit == 2 else (sw / (2 * lens) * (ry * ay) / (rx * ax) '
                    'if (fit == 1 or rx * ax >= ry * ay) else sw / (2 * lens))')
    sock.default_value = tan_half_fov_y(scene)
    return fc


def tan_half_fov_y(scene, cam=None):
    """tan(vertical fov / 2) of `cam` (the scene camera) for the scene's frame, as drive_tan_half_fov_y computes it."""
    cam = cam or scene.camera
    if cam is None or cam.type != 'CAMERA':
        return 0.414
    cd, r = cam.data, scene.render
    w, h = r.resolution_x * r.pixel_aspect_x, r.resolution_y * r.pixel_aspect_y
    if cd.sensor_fit == 'VERTICAL':
        return cd.sensor_height / (2 * cd.lens)
    if cd.sensor_fit == 'HORIZONTAL' or w >= h:
        return cd.sensor_width / (2 * cd.lens) * h / w
    return cd.sensor_width / (2 * cd.lens)


def _bubble_material():
    """createBubbles' MeshPhysicalNodeMaterial (white, transmission 1, IOR 1.06, clearcoat 1 at roughness 0,
    transparent) as EEVEE draws it in the frame the underwater pass reads. WebGPU's auto-enhance sets depthWrite = false
    on every transparent material, so the bubbles are in the colour and NOT in the depth or normal buffers: the pass
    fogs a bubble by what is behind it, and over the empty water roof replaces it with the roof (invisible there).
    EEVEE's Blended render method is the same contract (a blended surface is in Combined, not in the Depth / Normal
    passes). Its look: air in water bends the view by 1.06, so the body is see-through (Transparent), and the clear
    coat reflects by its own Fresnel (IOR 1.5: 4 % head on, all of it at the rim), a sharp highlight."""
    import bpy
    m = bpy.data.materials.get('uw_bubble') or bpy.data.materials.new('uw_bubble')
    m.use_nodes = True
    nt = m.node_tree
    nt.nodes.clear()
    tr = nt.nodes.new('ShaderNodeBsdfTransparent')
    tr.inputs['Color'].default_value = (1.0, 1.0, 1.0, 1.0)
    gl = nt.nodes.new('ShaderNodeBsdfGlossy')
    gl.inputs['Color'].default_value = (1.0, 1.0, 1.0, 1.0)
    gl.inputs['Roughness'].default_value = 0.0
    fr = nt.nodes.new('ShaderNodeFresnel')
    fr.inputs['IOR'].default_value = 1.5
    mx = nt.nodes.new('ShaderNodeMixShader')
    nt.links.new(fr.outputs['Fac'], mx.inputs['Fac'])
    nt.links.new(tr.outputs['BSDF'], mx.inputs[1])
    nt.links.new(gl.outputs['BSDF'], mx.inputs[2])
    out = nt.nodes.new('ShaderNodeOutputMaterial')
    nt.links.new(mx.outputs['Shader'], out.inputs['Surface'])
    m.surface_render_method = 'BLENDED'
    m.use_backface_culling = False
    return m


def underwater_bubbles(scene, camera, count=600, radius=6.0, range_y=8.0, seed=0):
    """underwater.js createBubbles: `count` clear air bubbles (icospheres 2.5 cm, IOR 1.06) rising round the
    camera's position at apply time, wobbling, growing 0.6x -> 2.1x as they rise, wrapping every range_y metres.
    Geometry Nodes on Scene Time, so the .blend plays on its own; seeded where WebGPU drew Math.random(). Drawn as the
    WebGPU frame had them: in colour only, not in the depth the pass reads (_bubble_material), casting no shadow
    (a three mesh casts none unless asked). The anchor (WebGPU's camPosUniform) is the 'uw_bubbles_anchor' node's
    second input in the 'uw_bubbles_gn' group (underwater's uniforms['cam_pos'])."""
    import bpy
    name = 'uw_bubbles'
    me = bpy.data.meshes.get(name) or bpy.data.meshes.new(name)
    ob = bpy.data.objects.get(name) or bpy.data.objects.new(name, me)
    if ob.name not in scene.collection.objects:
        scene.collection.objects.link(ob)
    ob.visible_shadow = False
    anchor = camera.matrix_world.translation.copy() if camera is not None else (0.0, 0.0, 0.0)
    ng = bpy.data.node_groups.get('uw_bubbles_gn') or bpy.data.node_groups.new('uw_bubbles_gn', 'GeometryNodeTree')
    ng.nodes.clear()
    if not any(s.in_out == 'OUTPUT' for s in ng.interface.items_tree if s.item_type == 'SOCKET'):
        ng.interface.new_socket(name='Geometry', in_out='OUTPUT', socket_type='NodeSocketGeometry')
    N, L = ng.nodes, ng.links

    def node(kind, **kw):
        n = N.new(kind)
        for k, v in kw.items():
            setattr(n, k, v)
        return n

    def math(op, a, b=None):
        n = node('ShaderNodeMath', operation=op)
        for i, x in enumerate((a, b)):
            if x is None:
                continue
            if isinstance(x, (int, float)):
                n.inputs[i].default_value = x
            else:
                L.new(x, n.inputs[i])
        return n.outputs[0]

    def rnd(lo, hi, sd):
        n = node('FunctionNodeRandomValue', data_type='FLOAT')
        ins = {s.identifier: s for s in n.inputs if s.enabled}
        fmin = next(s for s in n.inputs if s.name == 'Min' and s.type == 'VALUE')     # the float pair, not the vector
        fmax = next(s for s in n.inputs if s.name == 'Max' and s.type == 'VALUE')
        fmin.default_value, fmax.default_value = lo, hi
        ins['Seed'].default_value = seed * 7 + sd
        return next(s for s in n.outputs if s.name == 'Value' and s.type == 'VALUE')
    pts = node('GeometryNodePoints')
    pts.inputs['Count'].default_value = int(count)
    st = node('GeometryNodeInputSceneTime').outputs['Seconds']
    theta, rr = rnd(0.0, 2.0 * math_pi(), 1), math('POWER', rnd(0.0, 1.0, 2), 1.0 / 3.0)
    yoff, speed = rnd(-0.5 * range_y, 0.5 * range_y, 3), rnd(0.15, 0.40, 4)
    phase, wob = rnd(0.0, 2.0 * math_pi(), 5), rnd(0.04, 0.12, 6)
    r = math('MULTIPLY', rr, float(radius))
    y_local = math('SUBTRACT', math('FLOORED_MODULO', math('ADD', math('ADD', yoff, math('MULTIPLY', st, speed)),
                                                                 0.5 * range_y), float(range_y)), 0.5 * range_y)
    x_local = math('ADD', math('MULTIPLY', math('COSINE', theta), r),
                   math('MULTIPLY', math('SINE', math('ADD', math('MULTIPLY', st, 0.4), phase)), wob))
    z_local = math('ADD', math('MULTIPLY', math('SINE', theta), r),
                   math('MULTIPLY', math('COSINE', math('ADD', math('MULTIPLY', st, 0.3),
                                                        math('MULTIPLY', phase, 1.3))), wob))
    rise = math('DIVIDE', math('ADD', y_local, 0.5 * range_y), float(range_y))
    size = math('ADD', 0.6, math('MULTIPLY', rise, 1.5))
    comb = node('ShaderNodeCombineXYZ')                                 # three (x, y, z) -> Blender (x, -z, y)
    L.new(x_local, comb.inputs['X'])
    L.new(math('MULTIPLY', z_local, -1.0), comb.inputs['Y'])
    L.new(y_local, comb.inputs['Z'])
    add = node('ShaderNodeVectorMath', operation='ADD')
    add.name = add.label = 'uw_bubbles_anchor'                          # WebGPU's camPosUniform: set it to re-anchor
    L.new(comb.outputs[0], add.inputs[0])
    add.inputs[1].default_value = tuple(anchor)
    setp = node('GeometryNodeSetPosition')
    L.new(pts.outputs['Points'], setp.inputs['Geometry'])
    L.new(add.outputs[0], setp.inputs['Position'])
    ico = node('GeometryNodeMeshIcoSphere')
    ico.inputs['Radius'].default_value, ico.inputs['Subdivisions'].default_value = 0.025, 2
    inst = node('GeometryNodeInstanceOnPoints')
    L.new(setp.outputs['Geometry'], inst.inputs['Points'])
    L.new(ico.outputs['Mesh'], inst.inputs['Instance'])
    sc_v = node('ShaderNodeCombineXYZ')
    for k in ('X', 'Y', 'Z'):
        L.new(size, sc_v.inputs[k])
    L.new(sc_v.outputs[0], inst.inputs['Scale'])
    mat = _bubble_material()
    sm = node('GeometryNodeSetMaterial')
    sm.inputs['Material'].default_value = mat
    L.new(inst.outputs['Instances'], sm.inputs['Geometry'])
    out = node('NodeGroupOutput')
    L.new(sm.outputs['Geometry'], out.inputs[0])
    mod = ob.modifiers.get('uw_bubbles') or ob.modifiers.new('uw_bubbles', 'NODES')
    mod.node_group = ng
    return ob


