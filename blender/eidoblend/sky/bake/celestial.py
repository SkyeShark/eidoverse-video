"""GLSL generated per sky world: the red giant (redgiant.js) and the shattered moon's dust (asteroid_moon.js).

Both WebGPU shaders are built in JavaScript from authored constant lists (the flare slots, the fragment radii and
the streamer / plume picks) unrolled into the node graph; these functions unroll the same lists into GLSL, so the
shader the baker compiles is the one the scene's options describe. No bpy here.
"""


def _f(x):
    """A float literal GLSL accepts."""
    s = repr(float(x))
    return s if ('.' in s or 'e' in s) else s + '.0'


def _v2(v):
    return 'vec2(%s, %s)' % (_f(v[0]), _f(v[1]))


def _v3(v):
    return 'vec3(%s, %s, %s)' % (_f(v[0]), _f(v[1]), _f(v[2]))


# --------------------------------------------------------------------------------------------- red giant ---

def red_giant_glsl(flares, angular_radius=0.28, gran_scale=52.0, plasma_speed=0.5):
    """celestial(dir, col): Eanpa engine/redgiant.js shadeStar behind its 3.5-radius early out.

    flares: the FLARES slots, dicts with th, rate, ph0 and (front events, the paired sunspots) center=(x, y)."""
    import math
    out = []
    w = out.append
    w('// ---- the red giant (Eanpa engine/redgiant.js), generated by bake/celestial.py ----')
    w('const float RG_SIN_R = %s;' % _f(math.sin(angular_radius)))
    w('const float RG_COS_R = %s;' % _f(math.cos(angular_radius)))
    w('const float RG_GRAN = %s;' % _f(gran_scale))
    w('const float RG_PLASMA = %s;' % _f(plasma_speed))
    w('const float RG_EARLY_COS = %s;' % _f(math.cos(angular_radius * 3.5)))
    w('''float rgVn(vec2 p) {
    vec2 i = floor(p);
    vec2 f = fract(p);
    vec2 sm = f * f * f * (f * (f * 6.0 - 15.0) + 10.0);
    float a = h21(i);
    float b = h21(i + vec2(1.0, 0.0));
    float c = h21(i + vec2(0.0, 1.0));
    float d = h21(i + vec2(1.0, 1.0));
    return mix(mix(a, b, sm.x), mix(c, d, sm.x), sm.y);
}
float rgFbm3(vec2 p) { return rgVn(p) * 0.55 + rgVn(p * 2.3 + 19.7) * 0.28 + rgVn(p * 5.1 + 7.3) * 0.17; }
vec3 shadeStar(vec3 dir, vec3 col) {
    float lx = dot(dir, uStarRight) / RG_SIN_R;
    float ly = dot(dir, uStarUp) / RG_SIN_R;
    float face = step(RG_COS_R * 0.2, dot(dir, uStarDir));
    float rho = length(vec2(lx, ly));
    float surfaceScale = asin(clamp(rho, 0.0, 0.9995)) / max(rho, 0.001);
    vec2 p = vec2(lx, ly) * surfaceScale * RG_GRAN;
    float pt = uStarT * RG_PLASMA;
    vec2 w = (vec2(rgFbm3(p * 0.55 + pt * 0.55), rgFbm3(p * 0.55 - pt * 0.43 + 41.3)) - 0.5) * 1.9;
    float g = rgFbm3(p + w + vec2(pt * 0.22, 0.0)) * 0.82 + rgVn(p * 3.1 + w * 2.0 + vec2(0.0, pt * 0.9)) * 0.18;
    vec3 sCol = mix(vec3(0.42, 0.050, 0.015), vec3(1.05, 0.32, 0.06), smoothstep(0.35, 0.75, g));
    sCol = mix(sCol, vec3(1.85, 1.05, 0.45), smoothstep(0.78, 0.95, g));
    vec2 pg = vec2(lx, ly) * 1.15;
    float cell = rgFbm3(pg + vec2(uStarT * 0.006, uStarT * -0.004));
    sCol *= (cell - 0.5) * 0.55 + 1.0;
    float phi = atan(ly, lx);
    vec2 hpD = vec2(lx, ly) - vec2(0.34, -0.18);
    float hotK = exp(-dot(hpD, hpD) / 0.048) * (rgVn(vec2(uStarT * 0.02, 3.7)) * 0.4 + 0.8);
    sCol += vec3(0.55, 0.30, 0.12) * hotK;''')
    for f in flares:
        if not f.get('center'):
            continue
        th, c = f['th'], f['center']
        w('''    {   // a paired active region (umbra + penumbra) at %s
        vec2 q = vec2(lx, ly) - %s;
        vec2 tangent = %s;
        float a = length(q - tangent * 0.055);
        float b = length(q + tangent * 0.055);
        float spot = min(a, b) * mix(0.85, 1.15, g);
        float strength = sin(uStarT * 0.009 + %s) * 0.25 + 0.65;
        float penumbra = (1.0 - smoothstep(0.013, 0.038, spot)) * 0.38;
        float umbra = (1.0 - smoothstep(0.006, 0.017, spot)) * 0.5;
        sCol *= 1.0 - (penumbra + umbra) * strength;
    }''' % (_v2(c), _v2(c), _v2((-math.sin(th), math.cos(th))), _f(f['ph0'] * 6.28)))
    w('''    float muL = sqrt(max(1.0 - rho * rho, 0.0));
    sCol *= muL * 0.95 + 0.05;
    sCol *= mix(vec3(1.0, 0.60, 0.42), vec3(1.0, 1.03, 1.08), muL);
    float rimPatch = rgVn(vec2(phi * 2.2, uStarT * 0.11)) * 0.6 + 0.55;
    sCol += vec3(1.35, 0.32, 0.38) * (pow(1.0 - muL, 6.0) * 1.8) * rimPatch;
    sCol *= uStarTint;
    float inDisc = (1.0 - smoothstep(0.955, 1.045, rho)) * face;
    float glow = exp((rho - 1.0) * -16.0) * 0.50 + exp((rho - 1.0) * -6.5) * 0.30 + exp((rho - 1.0) * -2.2) * 0.12;
    float flare = 0.0;
    float footpoint = 0.0;
    vec2 p2 = vec2(lx, ly);''')
    for i, f in enumerate(flares):
        th, rate, ph0, c = f['th'], f['rate'], f['ph0'], f.get('center')
        env = 'max(env0, uFlareBoost)' if i == 0 else 'env0'
        c2 = _v2((math.cos(th), math.sin(th)))
        if c:
            anchor = _v2(c)
            rel = 'p2 - (%s - c2 * (loopR * 0.6))' % anchor
            emergence = 'smoothstep(-0.012, 0.012, dot(p2 - %s, c2))' % anchor
            blob_at = '%s + c2 * blobR' % anchor
            surf = 'abs(dot(p2 - %s, c2))' % anchor
        else:
            rel = 'p2 - c2 * (1.0 - loopR * 0.6)'
            emergence = 'smoothstep(0.955, 1.000, rho)'
            blob_at = 'c2 * (blobR + 1.0)'
            surf = 'abs(rho - 0.985)'
        w('''    {   // flare slot %d: th %s, rate %s, ph0 %s%s
        float ph = fract(uStarT * %s + %s);
        float cyc = floor(uStarT * %s + %s);
        float act = step(0.45, fract(sin(cyc * 12.9898 + %s) * 43758.5453));
        float env0 = pow(sin(clamp(ph * 1.3, 0.0, 1.0) * PI), 2.0) * act;
        float env = %s;
        vec2 c2 = %s;
        float loopR = env * 0.10 + 0.040;
        vec2 rel = %s;
        float la = atan(rel.y, rel.x);
        float fil = rgVn(vec2(la * 7.0, uStarT * 1.6 + %s)) * 0.55 + 0.55;
        float wobble = (fil - 0.55) * 0.035;
        float relLen = length(rel);
        float streak = rgVn(vec2(la * 15.0, relLen * 9.0 - uStarT * 0.8)) * 0.6 + 0.55;
        float band = (1.0 - smoothstep(0.008, 0.045, abs(relLen - (loopR * 0.82 + wobble)))) * 0.5
                   + (1.0 - smoothstep(0.008, 0.045, abs(relLen - (loopR * 1.0 + wobble)))) * 1.0
                   + (1.0 - smoothstep(0.008, 0.045, abs(relLen - (loopR * 1.16 + wobble)))) * 0.4;
        band += (1.0 - smoothstep(0.02, 0.12, abs(relLen - (loopR + wobble)))) * 0.4;
        band *= streak * fil * %s;
        float blobR = env * env * 0.42 + 0.06;
        float dBlob = length(p2 - (%s));
        float blob = (1.0 - smoothstep(0.012, 0.05, dBlob)) * smoothstep(0.75, 0.95, env) * 0.45;
        flare += (band * env * 0.7 + blob) * face;
        float feet = 1.0 - smoothstep(0.02, 0.10, abs(length(rel) - loopR) + %s * 2.0);
        footpoint += feet * env * 0.6;
    }''' % (i, _f(th), _f(rate), _f(ph0), (', front event at %s' % (c,)) if c else '',
            _f(rate), _f(ph0), _f(rate), _f(ph0), _f(th * 78.233), env, c2, rel, _f(ph0 * 40), emergence,
            blob_at, surf))
    w('''    float outside = (1.0 - inDisc) * face * step(1.0, rho);
    vec3 outc = mix(col, sCol, inDisc);
    outc += vec3(0.95, 0.22, 0.05) * glow * outside * 0.55;
    outc += vec3(1.5, 0.42, 0.10) * flare;
    outc += vec3(2.4, 1.05, 0.38) * flare * flare * 0.5;
    outc += vec3(2.3, 0.85, 0.25) * footpoint * inDisc;
    return outc;
}
vec3 celestial(vec3 dir, vec3 col) {
    // skip the convection and prominence noise away from the star (the Eanpa early out)
    return dot(dir, uStarDir) > RG_EARLY_COS ? shadeStar(dir, col) : col;
}''')
    return '\n'.join(out)


# ----------------------------------------------------------------------------------------- moon dust ---

def dust_glsl(rc, cent, arc_x, hero_r, piece_r, big, streams, steps=40):
    """dustLayer(dir, org, pix): Eanpa asteroid_moon.js's volumetric accretion dust (the 40-step march).

    rc the march sphere radius, cent the streak centroid (hero space), arc_x the streak half length, hero_r the
    largest fragment's radius, piece_r every fragment's radius (16), big the 7 biggest fragment indices, streams the 6
    streamer indices: all in the cluster's own units, from asteroid_moon.ShatteredMoon."""
    n = len(piece_r)
    out = []
    w = out.append
    w('// ---- the shattered moon\'s accretion dust (Eanpa engine/asteroid_moon.js), generated by bake/celestial.py ----')
    w('const float DUST_RC = %s;' % _f(rc))
    w('const vec3 DUST_CENT = %s;' % _v3(cent))
    w('const float DUST_ARCX = %s;' % _f(arc_x))
    w('const float DUST_HERO_R = %s;' % _f(hero_r))
    w('''float dustVn2(vec2 pp) {
    vec2 i2 = floor(pp);
    vec2 f2 = fract(pp);
    vec2 sm = f2 * f2 * (3.0 - 2.0 * f2);
    return mix(mix(h21(i2), h21(i2 + vec2(1.0, 0.0)), sm.x), mix(h21(i2 + vec2(0.0, 1.0)), h21(i2 + vec2(1.0, 1.0)), sm.x), sm.y);
}
float pcgHash(uint seed) {
    uint state = seed * 747796405u + 2891336453u;
    uint word = ((state >> ((state >> 28u) + 4u)) ^ state) * 277803737u;
    uint result = (word >> 22u) ^ word;
    return float(result) / 4294967296.0;
}
float dustCheap(vec3 pp) {
    float ccx = (pp.x - DUST_CENT.x) / (DUST_ARCX * 1.30);
    float ccy = (pp.y - DUST_CENT.y) / (DUST_HERO_R * 0.68);
    float ccz = (pp.z - DUST_CENT.z) / (DUST_HERO_R * 0.90);
    float ee = ccx * ccx + ccy * ccy + ccz * ccz;
    float d = 1.0 / (ee + 1.0) * 0.50;
    for (int pk = 0; pk < 3; pk++) {
        vec3 dpl = pp - uPlume(pk).xyz;
        float q = dot(dpl, dpl) / (DUST_HERO_R * DUST_HERO_R * 0.35);
        d += 1.0 / (q * q + 1.0) * 1.35;
    }''')
    for bi in big:
        hw = min(max(piece_r[bi] * 2.2, hero_r * 0.30), hero_r * 0.85)
        w('    { vec3 ds2 = pp - uPieceL(%d).xyz; d += exp(-dot(ds2, ds2) / %s) * 0.72; }' % (bi, _f(hw * hw)))
    w('''    return d;
}
vec4 dustMarch(vec3 ro, vec3 rd, vec2 pix) {
    float bq = dot(ro, rd);
    float cq = dot(ro, ro) - DUST_RC * DUST_RC;
    float sq = sqrt(max(bq * bq - cq, 0.0));
    float t0 = max(-bq - sq, 0.0);
    float t1 = max(-bq + sq, 0.0);
    float stepLen = (t1 - t0) / %s;
    if (!(stepLen > 0.0)) return vec4(0.0);
    float muP = max(dot(rd, uDustSunL), 0.0);
    float phaseF = 0.45 + muP * muP * muP * muP * muP * 2.4;
    vec3 cAcc = vec3(0.0);
    float aAcc = 0.0;
    float jitr = pcgHash(uint(pix.x) + uint(pix.y) * 65537u);
    vec3 p = ro + rd * t0 + rd * stepLen * (jitr * 0.9 + 0.05);
    for (int s = 0; s < %d; s++) {
        float n1 = dustVn2(vec2(p.x * (5.2 / DUST_RC) + uDustT * 0.05, p.z * (5.2 / DUST_RC)) + p.y * (2.6 / DUST_RC));
        float n2 = dustVn2(vec2(p.z * (9.5 / DUST_RC) - uDustT * 0.08, p.y * (9.5 / DUST_RC) + p.x * (3.5 / DUST_RC)));
        float n3 = dustVn2(vec2(p.x * (19.0 / DUST_RC) + uDustT * 0.11, p.y * (19.0 / DUST_RC) - p.z * (7.0 / DUST_RC)));
        float gate = smoothstep(0.16, 0.85, n1 * 0.50 + n2 * 0.30 + n3 * 0.20);
        float n4 = dustVn2(vec2(p.x * (38.0 / DUST_RC) + p.y * (17.0 / DUST_RC) + uDustT * 0.15,
                                p.z * (41.0 / DUST_RC) - p.y * (23.0 / DUST_RC)));
        float grain = n4 * n4;
        float pLen = length(p) + DUST_HERO_R * 0.1;
        float skew = dot(p, uDustSunL) / pLen * 0.45 + 1.0;
        float cx = (p.x - DUST_CENT.x) / (DUST_ARCX * 1.30);
        float cy = (p.y - DUST_CENT.y) / (DUST_HERO_R * 0.85);
        float cz = (p.z - DUST_CENT.z) / (DUST_HERO_R * 1.10);
        float q0 = (cx * cx + cy * cy + cz * cz) * skew * skew;
        float streak = 1.0 / (q0 + q0 * q0 * 0.6 + 1.0);
        float moat = smoothstep(0.2, 1.05, pLen / DUST_HERO_R);
        float envK = 1.0 - smoothstep(0.80, 1.0, length(p) / DUST_RC);
        float dens = streak * 0.10 * moat * (gate * 0.9 + 0.1) * envK;
        for (int pk = 0; pk < 3; pk++) {
            vec3 dpl = p - uPlume(pk).xyz;
            float q = dot(dpl, dpl) / (DUST_HERO_R * DUST_HERO_R * 0.35);
            dens += 1.0 / (q * q + 1.0) * 0.85 * (gate * 0.85 + 0.15) * envK;
        }''' % (_f(steps), steps))
    for bi in range(n):
        hw = min(max(piece_r[bi] * 2.2, hero_r * 0.30), hero_r * 0.85)
        w('        { vec3 ds2 = p - uPieceL(%d).xyz + uDustSunL * %s; dens += exp(-dot(ds2, ds2) / %s) * 0.30 * '
          '(gate * 0.8 + 0.2) * envK; }' % (bi, _f(hw * 0.55), _f(hw * hw)))
    for si in streams:
        w('        { vec3 e = uPieceL(%d).xyz; float hpar = clamp(dot(p, e) / (dot(e, e) + 1e-4), 0.0, 1.0); '
          'vec3 wv = p - e * hpar; float q3 = dot(wv, wv) / %s; '
          'dens += exp(-q3) * (1.0 - hpar * 0.40) * 0.55 * (gate * 0.8 + 0.2) * envK; }'
          % (si, _f(hero_r * hero_r * 0.013)))
    w('''        float form = smoothstep(0.22, 0.80, dens);
        dens *= form * 0.88 + 0.12;
        dens *= grain * 2.1 + 0.38;
        float dl1 = dustCheap(p + uDustSunL * (DUST_HERO_R * 0.28));
        float dl2 = dustCheap(p + uDustSunL * (DUST_HERO_R * 0.75));
        float denL = (dl1 + dl2) * (DUST_HERO_R * 0.30) * (gate * 0.8 + 0.4);
        float beers = exp(-denL * 3.2) + exp(-denL * 0.4) * 0.26;
        float powdered = 0.12 + pow(max(min(dens * 1.2, 1.0), 1e-6), 0.6);
        float lit = mix(powdered, 1.0, clamp(denL * 0.25, 0.0, 1.0));
        vec3 scol = vec3(0.36, 0.33, 0.28) * uDustSunCol * uDustGain * (beers * phaseF * lit);
        float sampleAlpha = 1.0 - exp(-dens * (stepLen / DUST_RC) * 8.5);
        float wgt = sampleAlpha * (1.0 - aAcc);
        cAcc += scol * wgt;
        aAcc += wgt;
        p += rd * stepLen;
    }
    // the opacity cap keeps the colour premultiplied by the capped opacity (Eanpa: cAcc * opacity / aAcc)
    float opacity = min(aAcc, 0.38);
    return vec4(cAcc * (opacity / max(aAcc, 1e-6)), opacity);
}
vec4 dustLayer(vec3 dir, vec3 org, vec2 pix) {
    if (uDustFade <= 0.0005) return vec4(0.0);
    mat3 toLocal = mat3(uDustM0, uDustM1, uDustM2);   // columns: world -> dust-local (rotation^T / scale)
    vec3 ro = toLocal * (org - uDustOrigin);
    vec3 rd = normalize(toLocal * dir);
    return dustMarch(ro, rd, pix) * uDustFade;        // premultiplied: both roots fade (Eanpa moonFade)
}''')
    return '\n'.join(out)
